truth.material_id_zx=uint16(X>21);
truth.cs_m_s_zx=1.75*ones(41); truth.cs_m_s_zx(X>21)=2.75;
truth.valid_mask_zx=true(41);
e=struct("purity",[.5 .7 .9 .98 1],"dnom",[0 .01 .05 1], ...
    "sws",[1.5 2 2.5 3],"frequency",[199 300]);
empty=table(zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1),VariableNames=[ ...
    "sws_bin","frequency_bin","purity_bin","diffusivity_bin", ...
    "example_count","independent_run_count","independent_condition_count"]);
summary=reqml.coverage.completeCoverageGrid(empty,e.sws,e.frequency, ...
    e.purity,e.dnom);
state=reqml.coverage.findCoverageDeficits(summary,MinimumExamples=4, ...
    MinimumIndependentRuns=2,MinimumIndependentConditions=1,IncludeComplete=true);
target=struct("center_indices_xz",[17 21], ...
    "requested_cell_key","s01_f01_p04_d02", ...
    "predicted_discrete_purity",1);
end
