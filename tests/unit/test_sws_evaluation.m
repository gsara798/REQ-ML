function tests = test_sws_evaluation
%TEST_SWS_EVALUATION Test partitioned SWS evaluation metrics.

tests = functiontests(localfunctions);

end

function setupOnce(~)

root = fileparts(fileparts(fileparts( ...
    mfilename("fullpath"))));

addpath(fullfile(root, "src"));

end

function testComputesCentralAndTailMetrics(testCase)

partition = [
    "train"
    "train"
    "validation"
    "validation"
    "test"
    "test"
    ];

cs_true = 2 * ones(6, 1);

cs_pred = [
    2.10
    2.18
    1.80
    2.40
    1.60
    2.00
    ];

error_m_s = cs_pred - cs_true;
error_percent = 100 * error_m_s ./ cs_true;
absolute_error_percent = abs(error_percent);

sws_table = table( ...
    cs_true, ...
    cs_pred, ...
    error_m_s, ...
    error_percent, ...
    absolute_error_percent, ...
    true(6, 1), ...
    VariableNames=[ ...
        "cs_true_m_s", ...
        "cs_pred_m_s", ...
        "cs_error_m_s", ...
        "cs_error_percent", ...
        "cs_absolute_error_percent", ...
        "sws_valid"]);

metrics = reqml.evaluation.evaluate_sws_predictions( ...
    sws_table, ...
    partition, ...
    "test_model");

verifyEqual(testCase, height(metrics), 3);

verifyEqual(testCase, ...
    metrics.partition, ...
    ["train"; "validation"; "test"]);

verifyEqual(testCase, ...
    metrics.sws_mape, ...
    [7; 15; 10], ...
    AbsTol=1e-12);

verifyEqual(testCase, ...
    metrics.sws_error_gt10_pct, ...
    [0; 50; 50], ...
    AbsTol=1e-12);

verifyEqual(testCase, ...
    metrics.sws_error_gt20_pct, ...
    [0; 0; 0], ...
    AbsTol=1e-12);

verifyEqual(testCase, ...
    metrics.sws_underestimate_pct, ...
    [0; 50; 50], ...
    AbsTol=1e-12);

end

function testRejectsMissingVariables(testCase)

invalid = table( ...
    [2; 2], ...
    VariableNames="cs_true_m_s");

partition = ["train"; "test"];

verifyError(testCase, ...
    @() reqml.evaluation.evaluate_sws_predictions( ...
        invalid, partition, "invalid"), ...
    "reqml:InvalidSwsPredictionTable");

end
