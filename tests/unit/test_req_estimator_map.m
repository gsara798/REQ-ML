function testExplicitCentersPreserveOrder(test_case)

[wavefield, cfg, feat_cfg] = make_fixture();

centers = [
    17, 17
    33, 25
    49, 41
];

out = reqml.estimators.req_estimator_map( ...
    wavefield, ...
    cfg, ...
    feat_cfg, ...
    "CenterIndices", centers, ...
    "ReturnFeatures", false, ...
    "ReturnFeatureTable", true, ...
    "StoreReqCurves", false);

verifyEqual(test_case, height(out.feature_table), 3);
verifyEqual(test_case, out.feature_table.cx, centers(:, 1));
verifyEqual(test_case, out.feature_table.cz, centers(:, 2));

verifyEqual(test_case, out.x_idx, centers(:, 1));
verifyEqual(test_case, out.z_idx, centers(:, 2));
verifyEqual(test_case, out.center_indices, centers);

verifySize(test_case, out.q_map, [3, 1]);
verifySize(test_case, out.cs_map, [3, 1]);
verifySize(test_case, out.valid_map, [3, 1]);

end


