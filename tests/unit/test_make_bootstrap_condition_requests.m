function testUsesExactConfiguredPhysicalRanges(testCase)

coverage = make_scientific_coverage();

requests = ...
    reqml.campaigns.makeBootstrapConditionRequests( ...
        coverage, ...
        BatchId="bootstrap_test");

sws_edges = coverage.sws_edges_m_s;
frequency_edges = coverage.frequency_edges_hz;
purity_edges = coverage.purity_edges;

dnom_edges = ...
    coverage.nominal_angular_coverage_edges;

for index = 1:numel(requests)
    request = requests(index);

    verifyEqual(testCase, ...
        request.target_sws_range_m_s, ...
        sws_edges( ...
            request.sws_bin: ...
            request.sws_bin + 1));

    verifyEqual(testCase, ...
        request.target_frequency_range_hz, ...
        frequency_edges( ...
            request.frequency_bin: ...
            request.frequency_bin + 1));

    verifyEqual(testCase, ...
        request.purity_range, ...
        purity_edges( ...
            request.purity_bin: ...
            request.purity_bin + 1));

    verifyEqual(testCase, ...
        request.diffusivity_range, ...
        dnom_edges( ...
            request.diffusivity_bin: ...
            request.diffusivity_bin + 1));

    verifyEqual(testCase, ...
        request.target_grid_spacing_m, ...
        coverage.discretization_pairs_m( ...
            request.discretization_bin, :), ...
        AbsTol=1e-15);

    verifyEqual(testCase, ...
        request.nominal_angular_coverage_range, ...
        request.diffusivity_range);

    verifyEqual(testCase, ...
        request.requested_cell_key, ...
        compose( ...
            "s%02d_f%02d_p%02d_d%02d_g%02d", ...
            request.sws_bin, ...
            request.frequency_bin, ...
            request.purity_bin, ...
            request.diffusivity_bin, ...
            request.discretization_bin));
end

end


function testDistributionIsDeterministic(testCase)

coverage = make_scientific_coverage();

a = reqml.campaigns.makeBootstrapConditionRequests( ...
    coverage, ...
    BatchId="bootstrap_test", ...
    PlannerSeed=42001);

b = reqml.campaigns.makeBootstrapConditionRequests( ...
    coverage, ...
    BatchId="bootstrap_test", ...
    PlannerSeed=42001);

verifyEqual(testCase, a, b);

expected_geometry = repmat( ...
    [ ...
        "homogeneous"
        "bilayer"
        "circular_inclusion"
    ], ...
    25, ...
    1);

expected_geometry = expected_geometry(1:75);

verifyEqual(testCase, ...
    string({a.geometry_family})', ...
    expected_geometry);

end


function testRequestsCanBeMaterialized(testCase)

coverage = make_scientific_coverage();

requests = ...
    reqml.campaigns.makeBootstrapConditionRequests( ...
        coverage, ...
        BatchId="bootstrap_test", ...
        PlannerSeed=42001);

conditions = ...
    reqml.campaigns.materializePhysicalConditions( ...
        requests, ...
        PlannerSeed=42001);

verifyEqual(testCase, numel(conditions), 75);

verifyTrue(testCase, ...
    all([conditions.realization_count]' == 2));

verifyEqual(testCase, ...
    string({conditions.condition_id})', ...
    string({requests.condition_id})');

end


