function testCreatesOneRequestPerSwsFrequencyDiscretizationBlock(testCase)

coverage = make_scientific_coverage();

requests = ...
    reqml.campaigns.makeBootstrapConditionRequests( ...
        coverage, ...
        BatchId="bootstrap_test", ...
        PlannerSeed=42001, ...
        RealizationsPerCondition=2);

verifyEqual(testCase, numel(requests), 75);

blocks = [
    [requests.sws_bin]', ...
    [requests.frequency_bin]', ...
    [requests.discretization_bin]'
    ];

verifyEqual(testCase, ...
    size(unique(blocks, "rows"), 1), ...
    75);

verifyEqual(testCase, ...
    unique([requests.sws_bin]'), ...
    (1:5)');

verifyEqual(testCase, ...
    unique([requests.frequency_bin]'), ...
    (1:5)');

verifyEqual(testCase, ...
    unique([requests.discretization_bin]'), ...
    (1:3)');

verifyEqual(testCase, ...
    [requests.realization_count]', ...
    repmat(2, 75, 1));

verifyEqual(testCase, ...
    [requests.planner_seed]', ...
    repmat(42001, 75, 1));

end


