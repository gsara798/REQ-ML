%% PREVIEW_HOMOGENEOUS_CONTROL_SPLIT_V1
% Build and inspect the grouped condition split for the homogeneous control.

clear;
clc;

this_file = mfilename("fullpath");
baseline_directory = fileparts(this_file);
experiments_directory = fileparts(baseline_directory);
repository_root = fileparts(experiments_directory);

addpath(repository_root);
repository_root = setup_reqml();

config_file = fullfile( ...
    repository_root, ...
    "configs", ...
    "baselines", ...
    "homogeneous_control_v1.json");

config = jsondecode(fileread(config_file));

dataset_file = fullfile( ...
    repository_root, ...
    config.dataset.examples_mat);

loaded = load(dataset_file, "examples");
examples = loaded.examples;

split = reqml.splits.make_grouped_condition_split( ...
    examples, ...
    Seed=config.split.seed, ...
    TrainFraction=config.split.train_fraction, ...
    ValidationFraction=config.split.validation_fraction, ...
    TestFraction=config.split.test_fraction);

integrity = reqml.splits.validate_split_integrity( ...
    examples, ...
    split);

assert(integrity.valid, integrity.summary);

output_directory = fullfile( ...
    repository_root, ...
    "outputs", ...
    "baselines", ...
    "homogeneous_control_v1", ...
    "split");

if isfolder(output_directory)
    error("reqml:BaselineSplitOutputExists", ...
        "Split output already exists: %s", ...
        output_directory);
end

mkdir(output_directory);

conditions = split.conditions;
summary = split.summary;

writetable( ...
    conditions, ...
    fullfile(output_directory, ...
        "condition_assignments.csv"));

writetable( ...
    summary, ...
    fullfile(output_directory, ...
        "split_summary.csv"));

split_manifest = struct();
split_manifest.schema_name = ...
    "reqml_baseline_split_manifest";
split_manifest.schema_version = "1.0";
split_manifest.baseline_id = ...
    string(config.baseline_id);
split_manifest.config_file = ...
    string(config_file);
split_manifest.dataset_id = ...
    string(config.dataset.dataset_id);
split_manifest.dataset_file = ...
    string(dataset_file);
split_manifest.target_column = ...
    string(config.dataset.target_column);
split_manifest.seed = split.seed;
split_manifest.group_columns = ...
    string(config.split.group_columns);
split_manifest.run_column = ...
    string(config.split.run_column);
split_manifest.train_fraction_requested = ...
    config.split.train_fraction;
split_manifest.validation_fraction_requested = ...
    config.split.validation_fraction;
split_manifest.test_fraction_requested = ...
    config.split.test_fraction;
split_manifest.integrity = integrity;
split_manifest.created = string(datetime( ...
    "now", ...
    "Format", ...
    "yyyy-MM-dd HH:mm:ss Z"));

file_id = fopen( ...
    fullfile(output_directory, ...
        "split_manifest.json"), ...
    "w");

if file_id < 0
    error("reqml:SplitManifestWriteFailed", ...
        "Could not create split manifest.");
end

cleanup = onCleanup(@() fclose(file_id));

fprintf(file_id, "%s", ...
    jsonencode(split_manifest, ...
        PrettyPrint=true));

clear cleanup

save( ...
    fullfile(output_directory, ...
        "split_assignments.mat"), ...
    "split", ...
    "-v7.3");

fprintf("\n============================================\n");
fprintf("Homogeneous control split completed\n");
fprintf("============================================\n");
disp(summary);
fprintf("Integrity: %s\n", integrity.summary);
fprintf("Output: %s\n", output_directory);
