function [conditions,runs,cfg] = materialize_design()

repo_root = string(fileparts(fileparts(fileparts(mfilename("fullpath")))));

cfg = jsondecode(fileread(fullfile( ...
    repo_root,"configs","validation","angular_aperture_N20_v1.json")));

cs_values = double(cfg.design.cs_m_s(:));
P_values = double(cfg.design.in_plane_count(:));
alpha_values = double(cfg.design.solid_angle_fraction(:));

N = double(cfg.design.direction_count);
f0 = double(cfg.design.frequency_hz);
nreal = double(cfg.design.realizations_per_condition);

ncond = numel(cs_values)*numel(P_values)*numel(alpha_values);
rows = cell(ncond,1);

k = 0;

for cidx = 1:numel(cs_values)
    cs = cs_values(cidx);

    for pidx = 1:numel(P_values)
        P = P_values(pidx);

        for aidx = 1:numel(alpha_values)

            alpha = alpha_values(aidx);
            k = k+1;

            rows{k} = struct( ...
                "condition_index",k, ...
                "condition_id",sprintf("cs%d_p%02d_a%02d",round(cs),P,aidx), ...
                "cs_true_m_s",cs, ...
                "frequency_hz",f0, ...
                "direction_count",N, ...
                "in_plane_count",P, ...
                "in_plane_fraction",P/N, ...
                "aperture_index",aidx, ...
                "solid_angle_fraction",alpha, ...
                "solid_angle_sr",alpha*4*pi);
        end
    end
end

conditions = struct2table(vertcat(rows{:}));

run_rows = cell(ncond*nreal,1);
ridx = 0;

for ci = 1:height(conditions)

    for r = 1:nreal

        ridx = ridx+1;

        seed = double(cfg.design.base_seed) + ...
            double(cfg.design.condition_seed_stride)*ci + r;

        run_rows{ridx} = struct( ...
            "run_index",ridx, ...
            "condition_id",string(conditions.condition_id(ci)), ...
            "run_id",string(conditions.condition_id(ci))+"_r"+sprintf("%02d",r), ...
            "cs_true_m_s",double(conditions.cs_true_m_s(ci)), ...
            "frequency_hz",f0, ...
            "direction_count",N, ...
            "in_plane_count",double(conditions.in_plane_count(ci)), ...
            "in_plane_fraction",double(conditions.in_plane_fraction(ci)), ...
            "aperture_index",double(conditions.aperture_index(ci)), ...
            "solid_angle_fraction",double(conditions.solid_angle_fraction(ci)), ...
            "solid_angle_sr",double(conditions.solid_angle_sr(ci)), ...
            "realization",r, ...
            "seed",seed);
    end
end

runs = struct2table(vertcat(run_rows{:}));

end
