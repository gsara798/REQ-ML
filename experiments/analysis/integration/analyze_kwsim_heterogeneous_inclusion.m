%% ANALYZE_KWSIM_HETEROGENEOUS_INCLUSION
% Analyze an existing frozen-REQ result for a two-material inclusion.
%
% Required environment variable:
%
%   REQ_ML_RESULT_DIR
%
% The estimator is not rerun. This script only reads:
%
%   kwsim_frozen_models_result.mat

clear;
clc;
close all;


%% Locate the existing result

result_directory = string( ...
    getenv("REQ_ML_RESULT_DIR"));

if strlength(result_directory) == 0
    error( ...
        "adaptive_req:MissingResultDirectory", ...
        "Set REQ_ML_RESULT_DIR before running this analysis.");
end

result_file = fullfile( ...
    result_directory, ...
    "kwsim_frozen_models_result.mat");

if ~isfile(result_file)
    error( ...
        "adaptive_req:MissingFrozenResult", ...
        "Result file was not found: %s", ...
        result_file);
end

loaded = load( ...
    result_file, ...
    "outcome");

if ~isfield(loaded, "outcome")
    error( ...
        "adaptive_req:InvalidFrozenResult", ...
        "MAT file does not contain outcome.");
end

outcome = loaded.outcome;

data = outcome.sample;
features = outcome.features;
predictions = outcome.predictions;
req_output = outcome.req_output;


%% Validate truth maps

if ~isfield(data.truth, "material_id_zx") || ...
        isempty(data.truth.material_id_zx)
    error( ...
        "adaptive_req:MissingMaterialIds", ...
        "The KWSIM sample does not contain material_id_zx.");
end

material_id_zx = double( ...
    data.truth.material_id_zx);

truth_sws_zx = double( ...
    data.truth.cs_m_s_zx);

if ~isequal( ...
        size(material_id_zx), ...
        size(truth_sws_zx))
    error( ...
        "adaptive_req:TruthSizeMismatch", ...
        "Material-ID and SWS maps have different sizes.");
end

background_id = 1;
inclusion_id = 2;

realized_ids = unique( ...
    material_id_zx(:));

if ~all(ismember( ...
        [background_id, inclusion_id], ...
        realized_ids))
    error( ...
        "adaptive_req:MissingExpectedMaterials", ...
        "Expected IDs [1 2], but found %s.", ...
        mat2str(realized_ids.'));
end


%% Classify each complete REQ window

number_of_sources = height(features);
half_win = double(req_output.half_win);
window_size = 2 * half_win + 1;

region_by_source = strings( ...
    number_of_sources, ...
    1);

background_fraction = nan( ...
    number_of_sources, ...
    1);

inclusion_fraction = nan( ...
    number_of_sources, ...
    1);

center_material_id = nan( ...
    number_of_sources, ...
    1);

patch_truth_mean_m_s = nan( ...
    number_of_sources, ...
    1);

patch_truth_std_m_s = nan( ...
    number_of_sources, ...
    1);


for source_row = 1:number_of_sources
    cx = round(double( ...
        features.cx(source_row)));

    cz = round(double( ...
        features.cz(source_row)));

    x_indices = ...
        (cx - half_win):(cx + half_win);

    z_indices = ...
        (cz - half_win):(cz + half_win);

    patch_ids = material_id_zx( ...
        z_indices, ...
        x_indices);

    patch_truth = truth_sws_zx( ...
        z_indices, ...
        x_indices);

    background_fraction(source_row) = mean( ...
        patch_ids == background_id, ...
        "all");

    inclusion_fraction(source_row) = mean( ...
        patch_ids == inclusion_id, ...
        "all");

    center_material_id(source_row) = ...
        material_id_zx(cz, cx);

    patch_truth_mean_m_s(source_row) = mean( ...
        patch_truth, ...
        "all", ...
        "omitnan");

    patch_truth_std_m_s(source_row) = std( ...
        patch_truth, ...
        0, ...
        "all", ...
        "omitnan");

    if all( ...
            patch_ids == background_id, ...
            "all")
        region_by_source(source_row) = ...
            "background_pure";

    elseif all( ...
            patch_ids == inclusion_id, ...
            "all")
        region_by_source(source_row) = ...
            "inclusion_pure";

    else
        region_by_source(source_row) = ...
            "mixed_interface";
    end
end


%% Attach region information to every model prediction

prediction_source_rows = double( ...
    predictions.source_row);

predictions.region = region_by_source( ...
    prediction_source_rows);

predictions.center_material_id = ...
    center_material_id( ...
        prediction_source_rows);

predictions.background_fraction = ...
    background_fraction( ...
        prediction_source_rows);

predictions.inclusion_fraction = ...
    inclusion_fraction( ...
        prediction_source_rows);

predictions.true_patch_purity = max( ...
    predictions.background_fraction, ...
    predictions.inclusion_fraction);

predictions.patch_truth_mean_m_s = ...
    patch_truth_mean_m_s( ...
        prediction_source_rows);

predictions.patch_truth_std_m_s = ...
    patch_truth_std_m_s( ...
        prediction_source_rows);


%% Build one source-window table

source_regions = table();

source_regions.source_row = ...
    (1:number_of_sources).';

source_regions.map_iz = ...
    double(features.map_iz(:));

source_regions.map_ix = ...
    double(features.map_ix(:));

source_regions.cx = ...
    double(features.cx(:));

source_regions.cz = ...
    double(features.cz(:));

source_regions.x_center_m = ...
    double(features.x_center_m(:));

source_regions.z_center_m = ...
    double(features.z_center_m(:));

source_regions.center_material_id = ...
    center_material_id(:);

source_regions.background_fraction = ...
    background_fraction(:);

source_regions.inclusion_fraction = ...
    inclusion_fraction(:);

source_regions.true_patch_purity = ...
    max( ...
        background_fraction(:), ...
        inclusion_fraction(:));

source_regions.region = ...
    region_by_source(:);

source_regions.patch_truth_mean_m_s = ...
    patch_truth_mean_m_s(:);

source_regions.patch_truth_std_m_s = ...
    patch_truth_std_m_s(:);


%% Metrics by model and region

model_names = unique( ...
    predictions.model_name, ...
    "stable");

region_names = [
    "all"
    "background_pure"
    "inclusion_pure"
    "mixed_interface"
];

metric_records = repmat( ...
    emptyMetricRecord(), ...
    0, ...
    1);


for model_name = model_names.'
    model_rows = predictions( ...
        predictions.model_name == model_name, :);

    for region_name = region_names.'
        if region_name == "all"
            rows = model_rows;
        else
            rows = model_rows( ...
                model_rows.region == region_name, :);
        end

        valid_rows = rows(rows.valid, :);

        record = emptyMetricRecord();

        record.model_name = model_name;
        record.region = region_name;
        record.N = height(rows);
        record.N_valid = height(valid_rows);

        record.valid_fraction = ...
            height(valid_rows) / ...
            max(height(rows), 1);

        if ~isempty(valid_rows)
            error_m_s = ...
                valid_rows.SWS_pred_m_s - ...
                valid_rows.SWS_true_m_s;

            record.mean_true_m_s = mean( ...
                valid_rows.SWS_true_m_s, ...
                "omitnan");

            record.mean_SWS_m_s = mean( ...
                valid_rows.SWS_pred_m_s, ...
                "omitnan");

            record.median_SWS_m_s = median( ...
                valid_rows.SWS_pred_m_s, ...
                "omitnan");

            record.RMSE_m_s = sqrt(mean( ...
                error_m_s.^2, ...
                "omitnan"));

            record.MAPE_pct = mean( ...
                valid_rows.abs_error_pct, ...
                "omitnan");

            record.median_APE_pct = median( ...
                valid_rows.abs_error_pct, ...
                "omitnan");

            record.bias_m_s = mean( ...
                error_m_s, ...
                "omitnan");

            record.bias_pct = mean( ...
                valid_rows.signed_error_pct, ...
                "omitnan");

            record.CoV_pct = ...
                100 * std( ...
                    valid_rows.SWS_pred_m_s, ...
                    0, ...
                    "omitnan") / ...
                max(abs(record.mean_SWS_m_s), eps);

            record.maximum_APE_pct = max( ...
                valid_rows.abs_error_pct);
        end

        metric_records(end + 1, 1) = ...
            record; %#ok<SAGROW>
    end
end

metrics_by_region = struct2table( ...
    metric_records);


%% Contrast recovery using pure windows only

contrast_records = repmat( ...
    emptyContrastRecord(), ...
    0, ...
    1);


for model_name = model_names.'
    rows = predictions( ...
        predictions.model_name == model_name & ...
        predictions.valid, :);

    background_rows = rows( ...
        rows.region == "background_pure", :);

    inclusion_rows = rows( ...
        rows.region == "inclusion_pure", :);

    record = emptyContrastRecord();

    record.model_name = model_name;
    record.N_background = height(background_rows);
    record.N_inclusion = height(inclusion_rows);

    if ~isempty(background_rows) && ...
            ~isempty(inclusion_rows)

        record.true_background_m_s = median( ...
            background_rows.SWS_true_m_s, ...
            "omitnan");

        record.true_inclusion_m_s = median( ...
            inclusion_rows.SWS_true_m_s, ...
            "omitnan");

        record.pred_background_mean_m_s = mean( ...
            background_rows.SWS_pred_m_s, ...
            "omitnan");

        record.pred_inclusion_mean_m_s = mean( ...
            inclusion_rows.SWS_pred_m_s, ...
            "omitnan");

        record.pred_background_median_m_s = median( ...
            background_rows.SWS_pred_m_s, ...
            "omitnan");

        record.pred_inclusion_median_m_s = median( ...
            inclusion_rows.SWS_pred_m_s, ...
            "omitnan");

        true_contrast = ...
            record.true_inclusion_m_s - ...
            record.true_background_m_s;

        predicted_mean_contrast = ...
            record.pred_inclusion_mean_m_s - ...
            record.pred_background_mean_m_s;

        predicted_median_contrast = ...
            record.pred_inclusion_median_m_s - ...
            record.pred_background_median_m_s;

        record.contrast_recovery_mean = ...
            predicted_mean_contrast / ...
            max(abs(true_contrast), eps);

        record.contrast_recovery_median = ...
            predicted_median_contrast / ...
            max(abs(true_contrast), eps);

        record.predicted_ratio_median = ...
            record.pred_inclusion_median_m_s / ...
            max( ...
                abs(record.pred_background_median_m_s), ...
                eps);
    end

    contrast_records(end + 1, 1) = ...
        record; %#ok<SAGROW>
end

contrast_summary = struct2table( ...
    contrast_records);


%% Reconstruct SWS maps

map_size = size(req_output.q_map);

sws_maps = struct();

for model_name = model_names.'
    rows = predictions( ...
        predictions.model_name == model_name, :);

    map = nan(map_size);

    linear_indices = sub2ind( ...
        map_size, ...
        double(rows.map_iz), ...
        double(rows.map_ix));

    map(linear_indices) = ...
        rows.SWS_pred_m_s;

    field_name = matlab.lang.makeValidName( ...
        char(model_name));

    sws_maps.(field_name) = map;
end


%% Save tables and MAT analysis

metrics_path = fullfile( ...
    result_directory, ...
    "metrics_by_region.csv");

contrast_path = fullfile( ...
    result_directory, ...
    "contrast_summary.csv");

predictions_path = fullfile( ...
    result_directory, ...
    "patch_results_with_regions.csv");

regions_path = fullfile( ...
    result_directory, ...
    "source_window_regions.csv");

analysis_path = fullfile( ...
    result_directory, ...
    "heterogeneous_inclusion_analysis.mat");

writetable( ...
    metrics_by_region, ...
    metrics_path);

writetable( ...
    contrast_summary, ...
    contrast_path);

writetable( ...
    predictions, ...
    predictions_path);

writetable( ...
    source_regions, ...
    regions_path);

save( ...
    analysis_path, ...
    "metrics_by_region", ...
    "contrast_summary", ...
    "source_regions", ...
    "predictions", ...
    "sws_maps", ...
    "-v7.3");


%% Plot truth and SWS maps

x_truth_mm = ...
    1e3 * double(data.axes.x_m);

z_truth_mm = ...
    1e3 * double(data.axes.z_m);

x_map_mm = ...
    1e3 * double( ...
        data.axes.x_m(req_output.x_idx));

z_map_mm = ...
    1e3 * double( ...
        data.axes.z_m(req_output.z_idx));

inclusion_mask = ...
    material_id_zx == inclusion_id;

color_limits = [1.5, 3.5];

figure_handle = figure( ...
    Visible="off", ...
    Position=[100, 100, 1300, 900]);

tiledlayout( ...
    2, ...
    2, ...
    TileSpacing="compact", ...
    Padding="compact");


nexttile;

imagesc( ...
    x_truth_mm, ...
    z_truth_mm, ...
    truth_sws_zx);

set(gca, "YDir", "normal");
axis image;
clim(color_limits);
colorbar;

xlabel("x (mm)");
ylabel("z (mm)");
title("Truth SWS");


for model_index = 1:numel(model_names)
    model_name = model_names(model_index);

    field_name = matlab.lang.makeValidName( ...
        char(model_name));

    map = sws_maps.(field_name);

    nexttile;

    imagesc( ...
        x_map_mm, ...
        z_map_mm, ...
        map);

    set(gca, "YDir", "normal");
    axis image;
    clim(color_limits);
    colorbar;

    hold on;

    contour( ...
        x_truth_mm, ...
        z_truth_mm, ...
        double(inclusion_mask), ...
        [0.5, 0.5], ...
        "k-", ...
        LineWidth=1.25);

    hold off;

    xlabel("x (mm)");
    ylabel("z (mm)");

    title( ...
        model_name, ...
        Interpreter="none");
end

colormap(turbo(256));

sgtitle( ...
    "KWSIM heterogeneous inclusion: SWS maps");

map_figure_path = fullfile( ...
    result_directory, ...
    "sws_maps_by_model.png");

exportgraphics( ...
    figure_handle, ...
    map_figure_path, ...
    Resolution=200);

close(figure_handle);


%% Print concise results

fprintf("\n============================================\n");
fprintf("Heterogeneous inclusion analysis\n");
fprintf("============================================\n");

fprintf( ...
    "Result directory:          %s\n", ...
    result_directory);

fprintf( ...
    "REQ window:               %d x %d pixels\n", ...
    window_size, ...
    window_size);

fprintf( ...
    "Background-pure windows:  %d\n", ...
    nnz(region_by_source == "background_pure"));

fprintf( ...
    "Inclusion-pure windows:   %d\n", ...
    nnz(region_by_source == "inclusion_pure"));

fprintf( ...
    "Mixed-interface windows:  %d\n\n", ...
    nnz(region_by_source == "mixed_interface"));

disp(metrics_by_region);

fprintf("\nContrast recovery:\n");
disp(contrast_summary);

fprintf("\nSaved SWS map:\n%s\n", ...
    map_figure_path);


%% Local functions

function record = emptyMetricRecord()

record = struct( ...
    model_name="", ...
    region="", ...
    N=0, ...
    N_valid=0, ...
    valid_fraction=NaN, ...
    mean_true_m_s=NaN, ...
    mean_SWS_m_s=NaN, ...
    median_SWS_m_s=NaN, ...
    RMSE_m_s=NaN, ...
    MAPE_pct=NaN, ...
    median_APE_pct=NaN, ...
    bias_m_s=NaN, ...
    bias_pct=NaN, ...
    CoV_pct=NaN, ...
    maximum_APE_pct=NaN);

end


function record = emptyContrastRecord()

record = struct( ...
    model_name="", ...
    N_background=0, ...
    N_inclusion=0, ...
    true_background_m_s=NaN, ...
    true_inclusion_m_s=NaN, ...
    pred_background_mean_m_s=NaN, ...
    pred_inclusion_mean_m_s=NaN, ...
    pred_background_median_m_s=NaN, ...
    pred_inclusion_median_m_s=NaN, ...
    contrast_recovery_mean=NaN, ...
    contrast_recovery_median=NaN, ...
    predicted_ratio_median=NaN);

end
