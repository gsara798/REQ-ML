function T = evaluate_one_run(sample_file, model_file)

fprintf("[%s] Starting evaluate_one_run\n", string(datetime("now")));
fprintf("[%s] Calling reqml.predictSWS...\n", string(datetime("now")));
t_predict = tic;

r = reqml.predictSWS( ...
    sample_file, ...
    Model=model_file, ...
    M=2, ...
    StepPixels=2, ...
    UseParallel=true);

fprintf("[%s] predictSWS finished in %.1f s\n", ...
    string(datetime("now")), toc(t_predict));

fprintf("[%s] Loading truth sample...\n", string(datetime("now")));
t_truth = tic;

data = reqml.io.load_wavefield_sample(sample_file);
fprintf("[%s] Truth sample loaded in %.1f s\n", ...
    string(datetime("now")), toc(t_truth));
fprintf("[%s] Computing truth/purity metrics...\n", string(datetime("now")));
t_metrics = tic;
e = r.patch_examples;

cs_map = double(data.truth.cs_m_s_zx);
material_map = data.truth.material_id_zx;
valid_truth = logical(data.truth.valid_mask_zx);

half_win = floor((double(r.metadata.patch_width_pixels)-1)/2);

n = height(e);

truth_cs = nan(n,1);
material_id = nan(n,1);
purity = nan(n,1);

for i = 1:n
    cx = round(double(e.cx(i)));
    cz = round(double(e.cz(i)));

    xidx = (cx-half_win):(cx+half_win);
    zidx = (cz-half_win):(cz+half_win);

    truth_cs(i) = cs_map(cz,cx);
    material_id(i) = double(material_map(cz,cx));

    [purity(i),~] = reqml.datasets.computeMaterialPatchPurity( ...
        material_map(zidx,xidx), ...
        valid_truth(zidx,xidx));
end

cs_pred = double(r.patch_predictions.cs_pred_m_s);
valid = logical(r.patch_predictions.sws_valid);

signed_error_percent = ...
    100*(cs_pred-truth_cs)./truth_cs;

absolute_error_percent = abs(signed_error_percent);

T = table( ...
    string(e.example_id), ...
    double(e.map_iz), ...
    double(e.map_ix), ...
    double(e.x_center_m), ...
    double(e.z_center_m), ...
    truth_cs, ...
    cs_pred, ...
    signed_error_percent, ...
    absolute_error_percent, ...
    material_id, ...
    purity, ...
    valid, ...
    VariableNames=[ ...
        "example_id","map_iz","map_ix","x_center_m","z_center_m", ...
        "cs_true_m_s","cs_pred_m_s","cs_error_percent", ...
        "cs_absolute_error_percent","material_id_center", ...
        "truth_material_purity","sws_valid"]);

fprintf("[%s] Truth/purity metrics finished in %.1f s\n", ...
    string(datetime("now")), toc(t_metrics));

fprintf("Patches: %d\n",height(T));
fprintf("Valid: %d\n",nnz(T.sws_valid));
fprintf("MAPE: %.3f %%\n", ...
    mean(T.cs_absolute_error_percent(T.sws_valid),"omitnan"));
fprintf("Bias: %.3f %%\n", ...
    mean(T.cs_error_percent(T.sws_valid),"omitnan"));

end
