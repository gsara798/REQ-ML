function [conditions,runs,cfg] = materialize_design()

repo_root = string(fileparts(fileparts(fileparts(mfilename("fullpath")))));

config_file = fullfile(repo_root,"configs","validation", ...
    "angular_aperture_inplane_diagnostic_v1.json");

cfg = jsondecode(fileread(config_file));

cs_values = double(cfg.design.cs_m_s(:));
p_values = double(cfg.design.in_plane_count(:));
N = double(cfg.design.direction_count);

rows = cell(numel(cs_values)*numel(p_values),1);

k = 0;

for ci = 1:numel(cs_values)
    for pi = 1:numel(p_values)

        k = k+1;

        cs = cs_values(ci);
        P = p_values(pi);

        rows{k} = struct( ...
            "condition_index",k, ...
            "condition_id",sprintf("cs%d_p%04d",round(cs),P), ...
            "cs_true_m_s",cs, ...
            "frequency_hz",double(cfg.design.frequency_hz), ...
            "direction_count",N, ...
            "in_plane_count",P, ...
            "in_plane_fraction",P/N, ...
            "solid_angle_fraction",1.0, ...
            "solid_angle_sr",double(cfg.design.solid_angle_sr));
    end
end

conditions = struct2table(vertcat(rows{:}));

run_rows = cell(height(conditions),1);

for i = 1:height(conditions)

    seed = ...
        double(cfg.design.base_seed) + ...
        double(cfg.design.condition_seed_stride)*i + 1;

    run_rows{i} = struct( ...
        "run_index",i, ...
        "condition_id",string(conditions.condition_id(i)), ...
        "run_id",string(conditions.condition_id(i))+"_r01", ...
        "cs_true_m_s",double(conditions.cs_true_m_s(i)), ...
        "frequency_hz",double(conditions.frequency_hz(i)), ...
        "direction_count",double(conditions.direction_count(i)), ...
        "in_plane_count",double(conditions.in_plane_count(i)), ...
        "in_plane_fraction",double(conditions.in_plane_fraction(i)), ...
        "solid_angle_fraction",1.0, ...
        "solid_angle_sr",double(conditions.solid_angle_sr(i)), ...
        "realization",1, ...
        "seed",seed);
end

runs = struct2table(vertcat(run_rows{:}));

end
