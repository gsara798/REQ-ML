function [conditions,runs,cfg] = materialize_design()

repo_root = string(fileparts(fileparts(fileparts(mfilename("fullpath")))));

config_file = fullfile(repo_root,"configs","validation", ...
    "angular_aperture_inplane_sweep_v1.json");

cfg = jsondecode(fileread(config_file));

cs = double(cfg.design.cs_m_s);
f0 = double(cfg.design.frequency_hz);
N = double(cfg.design.direction_count);

p_values = double(cfg.design.in_plane_count(:));
alpha_values = double(cfg.design.solid_angle_fraction(:));
nreal = double(cfg.design.realizations_per_condition);

ncond = numel(p_values)*numel(alpha_values);

condition_rows = cell(ncond,1);

k = 0;

for pidx = 1:numel(p_values)

    P = p_values(pidx);

    for ai = 1:numel(alpha_values)

        alpha = alpha_values(ai);

        k = k+1;

        condition_rows{k} = struct( ...
            "condition_index",k, ...
            "condition_id",sprintf("p%04d_a%02d",P,ai), ...
            "cs_true_m_s",cs, ...
            "frequency_hz",f0, ...
            "direction_count",N, ...
            "in_plane_count",P, ...
            "in_plane_fraction",P/N, ...
            "aperture_index",ai, ...
            "solid_angle_fraction",alpha, ...
            "solid_angle_sr",alpha*4*pi);
    end
end

conditions = struct2table(vertcat(condition_rows{:}));

run_rows = cell(ncond*nreal,1);

ridx = 0;

for ci = 1:height(conditions)

    for r = 1:nreal

        ridx = ridx+1;

        seed = ...
            double(cfg.design.base_seed) + ...
            double(cfg.design.condition_seed_stride)*ci + r;

        run_rows{ridx} = struct( ...
            "run_index",ridx, ...
            "condition_id",string(conditions.condition_id(ci)), ...
            "run_id",string(conditions.condition_id(ci)) + ...
                "_r" + sprintf("%02d",r), ...
            "cs_true_m_s",cs, ...
            "frequency_hz",f0, ...
            "direction_count",N, ...
            "in_plane_count",double(conditions.in_plane_count(ci)), ...
            "in_plane_fraction",double(conditions.in_plane_fraction(ci)), ...
            "aperture_index",double(conditions.aperture_index(ci)), ...
            "solid_angle_fraction", ...
                double(conditions.solid_angle_fraction(ci)), ...
            "solid_angle_sr", ...
                double(conditions.solid_angle_sr(ci)), ...
            "realization",r, ...
            "seed",seed);
    end
end

runs = struct2table(vertcat(run_rows{:}));

end
