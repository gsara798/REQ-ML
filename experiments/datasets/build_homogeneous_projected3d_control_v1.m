%% BUILD_HOMOGENEOUS_PROJECTED3D_CONTROL_V1
% Build the first complete homogeneous projected-3D REQ-ML control dataset.
%
% This dataset keeps the operational REQ configuration fixed:
%
%   M = 2
%   cs_guess = 3.0 m/s
%
% Frequency varies through the simulation campaign and remains a trainable
% operational predictor. M and cs_guess are registered as trainable variables,
% but are constant in this control dataset.
%
% This is a control dataset, not the final multi-M / multi-cs_guess training
% dataset.

clear;
clc;

this_file = mfilename("fullpath");
datasets_directory = fileparts(this_file);
experiments_directory = fileparts(datasets_directory);
repository_root = fileparts(experiments_directory);

addpath(repository_root);
repository_root = setup_reqml();

campaign_csv = fullfile( ...
    "/Users/sara/local/shear-wave-simulation-framework", ...
    "outputs", ...
    "campaigns", ...
    "scientific", ...
    "homogeneous_projected3d_clean_v1", ...
    "campaign_runs.csv");

dataset_id = "homogeneous_projected3d_control_v1";

output_directory = fullfile( ...
    repository_root, ...
    "outputs", ...
    "datasets", ...
    dataset_id);

if isfolder(output_directory)
    error( ...
        "reqml:DatasetOutputExists", ...
        "Dataset output already exists: %s", ...
        output_directory);
end

pool = gcp("nocreate");

if isempty(pool)
    pool = parpool("threads");
end

fprintf("Parallel workers: %d\n", ...
    pool.NumWorkers);

feature_config = ...
    reqml.config.default_feature_config( ...
        "M", 2, ...
        "cs_guess", 3.0, ...
        "gamma_win", 1.0, ...
        "pad_factor", 1, ...
        "smooth_sigma_2d", 1.0);

build_timer = tic;

dataset = ...
    reqml.datasets.build_dataset_from_campaign( ...
        campaign_csv, ...
        feature_config, ...
        DatasetId=dataset_id, ...
        MaxSamples=Inf, ...
        RequireBackend="swsynth", ...
        CsGuessMPerS=3.0, ...
        WindowWavelengths=2.0, ...
        MinimumPlacementsPerAxis=5, ...
        StepX=8, ...
        StepZ=8, ...
        StoreReqCurves=false, ...
        UseWindowParfor=true, ...
        OutputDirectory=output_directory, ...
        SaveOutputs=true);

elapsed_s = toc(build_timer);

fprintf("\n============================================\n");
fprintf("REQ-ML dataset build completed\n");
fprintf("============================================\n");
fprintf("Dataset ID : %s\n", dataset.dataset_id);
fprintf("Samples    : %d\n", dataset.sample_count);
fprintf("Examples   : %d\n", dataset.example_count);
fprintf("Elapsed    : %.1f s (%.2f min)\n", ...
    elapsed_s, elapsed_s / 60);
fprintf("Output     : %s\n", output_directory);
fprintf("Target q   : [%.4f, %.4f]\n", ...
    dataset.summary.target.minimum, ...
    dataset.summary.target.maximum);
fprintf("Trainable registry variables: %d\n", ...
    sum(dataset.summary.variable_registry.trainable));
fprintf("Nonconstant candidate predictors: %d\n", ...
    numel(dataset.summary.candidate_features));
fprintf("Unregistered variables: %d\n", ...
    numel(dataset.summary.unregistered_variables));

assert(dataset.sample_count == 300);
assert(dataset.example_count > 0);
assert(all(dataset.examples.target_valid));
assert(numel(unique(dataset.examples.example_id)) == ...
    dataset.example_count);
assert(isempty(dataset.summary.unregistered_variables));

required_artifacts = [
    dataset.paths.examples
    dataset.paths.samples
    dataset.paths.sample_summaries
    dataset.paths.variable_registry
    dataset.paths.dataset_summary
    dataset.paths.manifest
    ];

assert(all(isfile(required_artifacts)));
