function [conditions,runs,cfg] = materialize_design()

repo_root = string(fileparts(fileparts(fileparts(mfilename("fullpath")))));
config_file = fullfile(repo_root,"configs","validation", ...
    "angular_aperture_validation_v1.json");

cfg = jsondecode(fileread(config_file));

cs_values = double(cfg.design.cs_m_s(:));
fractions = double(cfg.design.solid_angle_fraction(:));
n_realizations = double(cfg.design.realizations_per_condition);

condition_rows = cell(numel(cs_values)*numel(fractions),1);

k = 0;

for ci = 1:numel(cs_values)
    for ai = 1:numel(fractions)

        k = k + 1;

        cs = cs_values(ci);
        alpha = fractions(ai);
        omega = 4*pi*alpha;

        condition_rows{k} = struct( ...
            "condition_index",k, ...
            "condition_id",sprintf("cs%d_a%02d",round(cs),ai), ...
            "cs_true_m_s",cs, ...
            "frequency_hz",double(cfg.design.frequency_hz), ...
            "solid_angle_fraction",alpha, ...
            "solid_angle_sr",omega, ...
            "direction_count",double(cfg.design.direction_count), ...
            "in_plane_count",double(cfg.design.in_plane_count));
    end
end

conditions = struct2table(vertcat(condition_rows{:}));

run_rows = cell(height(conditions)*n_realizations,1);

r = 0;

for i = 1:height(conditions)
    for realization = 1:n_realizations

        r = r + 1;

        seed = ...
            double(cfg.design.base_seed) + ...
            double(cfg.design.condition_seed_stride)* ...
                double(conditions.condition_index(i)) + ...
            realization;

        run_rows{r} = struct( ...
            "run_index",r, ...
            "condition_index",double(conditions.condition_index(i)), ...
            "condition_id",string(conditions.condition_id(i)), ...
            "run_id",sprintf("%s_r%02d", ...
                string(conditions.condition_id(i)),realization), ...
            "cs_true_m_s",double(conditions.cs_true_m_s(i)), ...
            "frequency_hz",double(conditions.frequency_hz(i)), ...
            "solid_angle_fraction", ...
                double(conditions.solid_angle_fraction(i)), ...
            "solid_angle_sr",double(conditions.solid_angle_sr(i)), ...
            "direction_count",double(conditions.direction_count(i)), ...
            "in_plane_count",double(conditions.in_plane_count(i)), ...
            "realization",realization, ...
            "seed",seed);
    end
end

runs = struct2table(vertcat(run_rows{:}));

end
