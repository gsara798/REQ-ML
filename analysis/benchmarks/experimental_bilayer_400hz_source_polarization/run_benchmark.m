function result = run_benchmark(config_file)
%RUN_BENCHMARK Analyze the completed SOURCE-Z/X controlled simulations.
% No simulation or model training is performed. Checkpoints permit analysis
% recovery without changing any scientific input or frozen model behavior.

if nargin<1 || isempty(config_file)
    root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    config_file=fullfile(root,'configs','benchmarks', ...
        'experimental_bilayer_400hz_source_polarization.json');
end
root=string(fileparts(fileparts(fileparts(fileparts(mfilename('fullpath'))))));
sim_root=string(getenv('SWSIM_ROOT'));
if strlength(sim_root)==0
    sim_root=fullfile(fileparts(root),'shear-wave-simulation-framework');
end
addpath(fullfile(root,'src'));
addpath(fullfile(sim_root,'src'));
addpath(fullfile(root,'analysis','benchmarks', ...
    'experimental_bilayer_400hz','aia'));
c=jsondecode(fileread(config_file));
vars=struct('SWSIM_ROOT',sim_root);
model_file=reqml.config.resolveWorkspacePath(c.model_file, ...
    RepositoryRoot=root,Variables=vars);
output_root=reqml.config.resolveWorkspacePath(c.output_root, ...
    RepositoryRoot=root,Variables=vars);
checkpoint=fullfile(output_root,'analysis_checkpoint.mat');
if isfolder(output_root) && isfile(fullfile(output_root,'manifest.json'))
    error('reqml:benchmark:OutputExists', ...
        'Completed source-polarization output already exists: %s',output_root);
end
folders=["component_samples","figures","spectra"];
for name=folders
    folder=fullfile(output_root,name); if ~isfolder(folder), mkdir(folder); end
end
bundle=load(model_file,'model','model_metadata','predictor_names');
if isfile(checkpoint)
    saved=load(checkpoint,'parts','products'); parts=saved.parts; products=saved.products;
else
    parts=cell(numel(c.conditions),1); products=cell(numel(c.conditions),1);
end

for index=1:numel(c.conditions)
    if ~isempty(parts{index}), continue; end
    spec=c.conditions(index);
    fprintf('Analyzing %s SOURCE-%s (%d/%d)\n',spec.id, ...
        spec.source_polarization,index,numel(c.conditions));
    result_file=reqml.config.resolveWorkspacePath(spec.result_file, ...
        RepositoryRoot=root,Variables=vars);
    loaded=load(result_file,'result'); simulation=loaded.result;
    [uz,uz_file]=make_sample(simulation,"axial_total",output_root,index);
    [ux,ux_file]=make_sample(simulation,"lateral_total",output_root,index);
    q0uz=reqml.benchmarks.sourcePolarization.predictQ0Data(uz,bundle, ...
        M=c.req.M,StepPixels=c.req.step_pixels,UseParallel=true);
    q0ux=reqml.benchmarks.sourcePolarization.predictQ0Data(ux,bundle, ...
        M=c.req.M,StepPixels=c.req.step_pixels,UseParallel=true);
    interface_z=NaN; if string(spec.id)=="BILAYER", interface_z=c.interface_z_m; end
    pUz=reqml.benchmarks.experimentalBilayer.buildPatchTable(spec.id, ...
        "REQ-ML Q0",q0uz.cs_map,q0uz.x_idx,q0uz.z_idx, ...
        q0uz.metadata.patch_width_pixels,uz,M=c.req.M,InterfaceZM=interface_z);
    pUx=reqml.benchmarks.experimentalBilayer.buildPatchTable(spec.id, ...
        "REQ-ML Q0",q0ux.cs_map,q0ux.x_idx,q0ux.z_idx, ...
        q0ux.metadata.patch_width_pixels,ux,M=c.req.M,InterfaceZM=interface_z);
    physical=struct('dx',uz.dx_m,'dz',uz.dz_m,'f0',uz.frequency_hz, ...
        'cs_bg',c.req.cs_guess_m_s);
    feature_config=reqml.config.default_feature_config( ...
        M=c.req.M,cs_guess=c.req.cs_guess_m_s);
    theory=reqml.estimators.req_estimator_map(uz.wavefield_zx,physical, ...
        feature_config,StepX=c.req.step_pixels,StepZ=c.req.step_pixels, ...
        QuantileMode='theory_discrete', ...
        TheoryFieldType=c.theory_discrete.field_type, ...
        TheoryMode=c.theory_discrete.theory_mode,ReturnFeatures=false, ...
        ReturnFeatureTable=false,StoreReqCurves=false,UseWindowParfor=true);
    pTheory=reqml.benchmarks.experimentalBilayer.buildPatchTable(spec.id, ...
        "REQ theory-discrete",theory.cs_map,theory.x_idx,theory.z_idx, ...
        theory.win_size,uz,M=c.req.M,InterfaceZM=interface_z);
    [aia_cs,~,~,~,aia_diag]=aia_estimator_RSWE(uz.wavefield_zx, ...
        uz.dx_m,uz.dz_m,uz.frequency_hz,'M',c.aia.M, ...
        'cs_guess',c.aia.cs_guess_m_s,'StepX',c.aia.step_pixels, ...
        'StepZ',c.aia.step_pixels,'EdgeMode',c.aia.edge_mode, ...
        'NumAngles',c.aia.num_angles,'AutoDecimate',c.aia.auto_decimate, ...
        'UseParfor',c.aia.use_parfor);
    pAia=reqml.benchmarks.experimentalBilayer.buildPatchTable(spec.id, ...
        "AIA source-faithful",aia_cs,aia_diag.cx_list,aia_diag.cz_list, ...
        [aia_diag.win_z aia_diag.win_x],uz,M=c.aia.M,InterfaceZM=interface_z);
    pUz.observed_component(:)="Uz"; pUx.observed_component(:)="Ux";
    pTheory.observed_component(:)="Uz"; pAia.observed_component(:)="Uz";
    allp=[pUz;pUx;pTheory;pAia];
    allp.source_polarization(:)=string(spec.source_polarization);
    allp.condition_key(:)=string(spec.source_polarization)+"_"+string(spec.id);
    parts{index}=allp;
    products{index}=struct('condition',string(spec.id), ...
        'source_polarization',string(spec.source_polarization), ...
        'result_file',string(result_file),'uz_file',uz_file,'ux_file',ux_file, ...
        'uz',uz,'ux',ux,'q0uz',q0uz,'q0ux',q0ux,'theory',theory, ...
        'aia_cs',aia_cs,'aia_diag',aia_diag, ...
        'vector_metrics',vector_metrics(ux,uz,spec));
    save(checkpoint,'parts','products','c','-v7.3');
end

patches=vertcat(parts{:});
patches=mark_support(patches);
group_names=["source_polarization","condition","observed_component", ...
    "estimator","M","center_material_id"];
summary=reqml.benchmarks.experimentalBilayer.summarizePatches( ...
    patches,group_names,CommonSupportOnly=false);
primary=patches(patches.observed_component=="Uz",:);
primary_summary=reqml.benchmarks.experimentalBilayer.summarizePatches(primary, ...
    ["source_polarization","condition","estimator","M", ...
    "center_material_id"]);
source_comparison=reqml.benchmarks.sourcePolarization.compareSourceSummaries( ...
    primary_summary);
bilayer=primary(primary.condition=="BILAYER",:);
by_distance=reqml.benchmarks.experimentalBilayer.summarizePatches(bilayer, ...
    ["source_polarization","estimator","M","center_material_id", ...
    "distance_bin"]);
by_purity=reqml.benchmarks.experimentalBilayer.summarizePatches(bilayer, ...
    ["source_polarization","estimator","M","center_material_id", ...
    "purity_bin"]);
vector_parts=cellfun(@(x) x.vector_metrics,products,'UniformOutput',false);
vector_summary=vertcat(vector_parts{:});
[spectral_summary,radial_curves,angular_curves]= ...
    spectral_diagnostics(products,c);
training_audit=build_training_audit(root,sim_root);

writetable(patches,fullfile(output_root,'patch_results.csv'));
writetable(summary,fullfile(output_root,'summary_all_controls.csv'));
writetable(primary_summary,fullfile(output_root,'summary_primary_estimators.csv'));
writetable(source_comparison,fullfile(output_root,'summary_source_z_vs_x.csv'));
writetable(by_distance,fullfile(output_root,'summary_error_vs_distance.csv'));
writetable(by_purity,fullfile(output_root,'summary_error_vs_purity.csv'));
writetable(vector_summary,fullfile(output_root,'vector_wavefield_summary.csv'));
writetable(spectral_summary,fullfile(output_root,'spectral_region_summary.csv'));
writetable(radial_curves,fullfile(output_root,'spectra','radial_curves.csv'));
writetable(angular_curves,fullfile(output_root,'spectra','angular_curves.csv'));
writetable(training_audit,fullfile(output_root,'training_domain_audit.csv'));
write_experimental_registry(c,output_root);
make_figures(products,patches,by_distance,by_purity,spectral_summary, ...
    radial_curves,output_root);
geometry=reqml.benchmarks.sourcePolarization.copyGeometryAudit( ...
    sim_root,output_root);
save(fullfile(output_root,'benchmark_results.mat'),'patches','summary', ...
    'primary_summary','source_comparison','by_distance','by_purity','vector_summary', ...
    'spectral_summary','radial_curves','angular_curves','training_audit', ...
    'c','-v7.3');
write_manifest(output_root,c,config_file,model_file,products,geometry);
delete(checkpoint);
result=struct('output_root',output_root,'patches',patches, ...
    'summary',summary,'primary_summary',primary_summary, ...
    'source_comparison',source_comparison, ...
    'by_distance',by_distance,'by_purity',by_purity, ...
    'vector_summary',vector_summary,'spectral_summary',spectral_summary, ...
    'training_audit',training_audit);
end

function [data,filename]=make_sample(simulation,component,root,index)
wavefield_sample=kwsim.samples.buildWavefieldSample(simulation, ...
    Quantity="displacement",Component=component);
filename=fullfile(root,'component_samples',sprintf('%02d_%s.mat',index,component));
save(filename,'wavefield_sample','-v7.3');
data=reqml.io.load_wavefield_sample(filename);
end

function t=vector_metrics(ux,uz,spec)
a=abs(ux.wavefield_zx); b=abs(uz.wavefield_zx); ratio=a./max(b,eps);
t=table(string(spec.source_polarization),string(spec.id),numel(a), ...
    median(a,'all'),median(b,'all'),sqrt(mean(a.^2,'all')), ...
    sqrt(mean(b.^2,'all')),median(ratio,'all'),prctile(ratio(:),25), ...
    prctile(ratio(:),75), ...
    'VariableNames',{'source_polarization','condition','N_pixels', ...
    'median_abs_Ux','median_abs_Uz','rms_abs_Ux','rms_abs_Uz', ...
    'median_Ux_Uz_ratio','Ux_Uz_ratio_q25','Ux_Uz_ratio_q75'});
end

function p=mark_support(p)
p.common_support=false(height(p),1);
primary=p.observed_component=="Uz";
estimators=unique(p.estimator(primary));
[g,~]=findgroups(p.source_polarization,p.condition,p.cx,p.cz);
count=splitapply(@(e,v) numel(unique(e(v))),p.estimator,p.valid,g);
p.common_support=primary & p.valid & count(g)==numel(estimators);
% Ux is a single-estimator control and retains its own native valid support.
p.common_support(p.observed_component=="Ux")=p.valid(p.observed_component=="Ux");
end

function [summary,radial,angular]=spectral_diagnostics(products,c)
summary_rows={}; radial_rows={}; angular_rows={}; nr=0; nk=0; na=0;
for pi=1:numel(products)
    product=products{pi}; regions=c.regions(string({c.regions.condition})==product.condition);
    for component=["Uz","Ux"]
        if component=="Uz", data=product.uz; q0=product.q0uz; else, data=product.ux; q0=product.q0ux; end
        for ri=1:numel(regions)
            [~,ix]=min(abs(q0.x_mm-1e3*regions(ri).x_m));
            [~,iz]=min(abs(q0.z_mm-1e3*regions(ri).z_m));
            cx=q0.x_idx(ix); cz=q0.z_idx(iz); qpred=q0.q_map(iz,ix);
            physical=struct('dx',data.dx_m,'dz',data.dz_m, ...
                'f0',data.frequency_hz,'cs_bg',c.req.cs_guess_m_s);
            fc=reqml.config.default_feature_config(M=c.req.M, ...
                cs_guess=c.req.cs_guess_m_s);
            d=reqml.estimators.req_estimator_map(data.wavefield_zx,physical,fc, ...
                CenterIndices=[cx cz],QuantileMode='fixed', ...
                FixedQuantile=qpred,ReturnFeatures=true, ...
                ReturnFeatureTable=true,StoreReqCurves=true);
            curve=d.req_curves{1}; feat=d.features{1};
            rad=reqml.features.extract_radial_features( ...
                max(curve.Ssm,0)./(sum(max(curve.Ssm,0),'all')+eps), ...
                curve.KR,fc);
            ang=reqml.features.extract_angular_features( ...
                max(curve.Ssm,0)./(sum(max(curve.Ssm,0),'all')+eps), ...
                curve.TH,curve.KR,rad,fc);
            material=data.truth.material_id_zx(cz,cx); truth=data.truth.cs_m_s_zx(cz,cx);
            h=floor(d.win_size/2); mask=data.truth.material_id_zx(cz-h:cz+h,cx-h:cx+h);
            purity=mean(mask(:)==material);
            dist=NaN; if product.condition=="BILAYER", dist=1e3*(data.axes.z_m(cz)-c.interface_z_m); end
            companion=product.uz; if component=="Uz", companion=product.ux; end
            local_this=data.wavefield_zx(cz-h:cz+h,cx-h:cx+h);
            local_other=companion.wavefield_zx(cz-h:cz+h,cx-h:cx+h);
            if component=="Uz", local_ratio=rms(abs(local_other),'all')/max(rms(abs(local_this),'all'),eps); else, local_ratio=rms(abs(local_this),'all')/max(rms(abs(local_other),'all'),eps); end
            peak_count=count_peaks(rad.Prad_plot);
            centroid=sum(rad.k_cent_plot.*rad.Prad_plot)/(sum(rad.Prad_plot)+eps);
            bandwidth=sqrt(sum(rad.Prad_plot.*(rad.k_cent_plot-centroid).^2)/(sum(rad.Prad_plot)+eps));
            [~,pk]=max(rad.Prad_plot); peak_k=rad.k_cent_plot(pk);
            nr=nr+1; summary_rows{nr}=table(product.source_polarization,component, ...
                product.condition,string(regions(ri).name),cx,cz, ...
                data.axes.x_m(cx),data.axes.z_m(cz),qpred,d.k_map(1),d.cs_map(1), ...
                truth,d.cs_map(1)-truth,100*(d.cs_map(1)-truth)/truth, ...
                material,purity,dist,local_ratio,peak_k,centroid,bandwidth, ...
                peak_count,feat.radial_entropy,feat.width_75_25_rel, ...
                feat.width_90_10_rel,feat.ang_entropy,feat.circ_var, ...
                feat.dom_dir_frac,feat.window_max_frac, ...
                exp(feat.ang_entropy*log(numel(ang.Pang))), ...
                'VariableNames',{'source_polarization','observed_component', ...
                'condition','region','cx','cz','x_m','z_m','q_pred','k_q', ...
                'estimate_m_s','truth_m_s','signed_error_m_s', ...
                'relative_error_percent','material_id','window_purity', ...
                'signed_distance_to_interface_mm','local_Ux_Uz_rms_ratio', ...
                'dominant_peak_k_rad_m','spectral_centroid_k_rad_m', ...
                'spectral_bandwidth_k_rad_m','prominent_peak_count', ...
                'radial_entropy','width_75_25_rel','width_90_10_rel', ...
                'ang_entropy','circ_var','dom_dir_frac','window_max_frac', ...
                'effective_angular_bins'});
            nk=nk+1; radial_rows{nk}=table( ...
                repmat(product.source_polarization,numel(rad.k_cent_plot),1), ...
                repmat(component,numel(rad.k_cent_plot),1), ...
                repmat(product.condition,numel(rad.k_cent_plot),1), ...
                repmat(string(regions(ri).name),numel(rad.k_cent_plot),1), ...
                rad.k_cent_plot(:),rad.Prad_plot(:),rad.Frad_plot(:), ...
                repmat(qpred,numel(rad.k_cent_plot),1), ...
                repmat(d.k_map(1),numel(rad.k_cent_plot),1), ...
                'VariableNames',{'source_polarization','observed_component', ...
                'condition','region','k_rad_m','normalized_energy', ...
                'cumulative_energy','q_pred','k_q'});
            na=na+1; angular_rows{na}=table( ...
                repmat(product.source_polarization,numel(ang.th_deg),1), ...
                repmat(component,numel(ang.th_deg),1), ...
                repmat(product.condition,numel(ang.th_deg),1), ...
                repmat(string(regions(ri).name),numel(ang.th_deg),1), ...
                ang.th_deg(:),ang.Pang(:), ...
                'VariableNames',{'source_polarization','observed_component', ...
                'condition','region','theta_deg','normalized_energy'});
        end
    end
end
summary=vertcat(summary_rows{:}); radial=vertcat(radial_rows{:}); angular=vertcat(angular_rows{:});
end

function n=count_peaks(y)
y=movmean(double(y(:)),3); threshold=.2*max(y); n=0;
for i=2:numel(y)-1
    if y(i)>y(i-1) && y(i)>=y(i+1) && y(i)>=threshold, n=n+1; end
end
end

function audit=build_training_audit(root,sim_root)
config_file=fullfile(root,'configs','homogeneous','homogeneous_cartesian_q0_v2.json');
base_file=fullfile(sim_root,'configs','swsynth','scientific', ...
    'reqml_eikonal_training_v1','homogeneous_base.json');
audit=table(["Q0 v2 homogeneous Eikonal";"Controlled SOURCE-X candidate"], ...
    ["random transverse vector per direction";"finite contact X"], ...
    ["sampled direction ensemble";"predominantly lateral-to-FOV propagation"], ...
    ["axial Uz scalar";"axial Uz scalar"],[true;false], ...
    ["Polarization vectors are provenance; only scalar Uz is stored."; ...
    "No equivalent fixed finite-contact SOURCE-X to observed Uz condition."], ...
    [string(config_file);string(base_file)], ...
    'VariableNames',{'dataset_regime','source_polarization', ...
    'propagation_direction','observed_component','included_in_q0_v2_training', ...
    'notes','audited_config'});
end

function write_experimental_registry(c,root)
names=string(fieldnames(c.experimental_optional)); names(names=="enabled")=[];
paths=strings(numel(names),1); exists=false(numel(names),1); preprocessing=strings(numel(names),1);
for i=1:numel(names)
    paths(i)=string(c.experimental_optional.(names(i))); exists(i)=isfile(paths(i));
    if contains(lower(names(i)),"raw"), preprocessing(i)="raw"; else, preprocessing(i)="donut"; end
end
t=table(names,paths,exists,preprocessing); writetable(t,fullfile(root,'experimental_input_registry.csv'));
end

function make_figures(products,p,distance,purity,spectral,radial,root)
folder=fullfile(root,'figures'); labels=["H_SOFT","H_STIFF","BILAYER"];
for source=["Z","X"]
    fig=figure('Visible','off','Color','w','Position',[50 50 1600 1100]);
    tiledlayout(3,6,'TileSpacing','compact','Padding','compact');
    selected=products(cellfun(@(x) x.source_polarization==source,products));
    maxamp=max(cellfun(@(x) max([abs(x.ux.wavefield_zx),abs(x.uz.wavefield_zx)],[],'all'),selected));
    for i=1:3
        q=selected{find(cellfun(@(x) x.condition==labels(i),selected),1)};
        ux=q.ux.wavefield_zx; uz=q.uz.wavefield_zx; x=1e3*q.ux.axes.x_m; z=1e3*q.ux.axes.z_m;
        maps={abs(ux),abs(uz),angle(ux),angle(uz),cos(angle(ux)),cos(angle(uz))};
        titles=["|Ux|","|Uz|","phase Ux","phase Uz","cos phase Ux","cos phase Uz"];
        for j=1:6
            nexttile((i-1)*6+j); imagesc(x,z,maps{j}); axis image;
            if j<=2, clim([0 maxamp]); elseif j<=4, clim([-pi pi]); else, clim([-1 1]); end
            title(labels(i)+" "+titles(j),'Interpreter','none'); colorbar;
        end
    end
    sgtitle("SOURCE-"+source+" vector harmonic displacement"); save_png(fig,folder,"vector_fields_source_"+lower(source));
end
% Ratio maps, including the explicitly requested dB convention.
fig=figure('Visible','off','Color','w','Position',[50 50 1200 650]); tiledlayout(2,3,'TileSpacing','compact');
for i=1:numel(products)
    q=products{i}; ratio=20*log10(abs(q.ux.wavefield_zx)./max(abs(q.uz.wavefield_zx),eps));
    nexttile; imagesc(1e3*q.ux.axes.x_m,1e3*q.ux.axes.z_m,ratio); axis image; clim([-30 30]); colorbar;
    title("SOURCE-"+q.source_polarization+" "+q.condition,'Interpreter','none');
end
sgtitle('20 log_{10}(|Ux|/|Uz|) (dB)'); save_png(fig,folder,'vector_component_ratio_db');
estimators=["REQ-ML Q0","REQ theory-discrete","AIA source-faithful"];
for ei=1:numel(estimators)
    fig=figure('Visible','off','Color','w','Position',[50 50 1200 650]); tiledlayout(2,3,'TileSpacing','compact');
    for si=1:2
        source=["Z","X"]; source=source(si);
        for ci=1:3
            q=p(p.source_polarization==source&p.condition==labels(ci)& ...
                p.observed_component=="Uz"&p.estimator==estimators(ei),:);
            [map,x,z]=reqml.benchmarks.sourcePolarization.patchesToGrid(q);
            nexttile((si-1)*3+ci); imagesc(x,z,map); axis image; clim([1.4 3.4]); colorbar;
            xlabel('x (mm)'); ylabel('z (mm)');
            title("SOURCE-"+source+" "+labels(ci),'Interpreter','none');
        end
    end
    sgtitle(estimators(ei)+" observing Uz (native estimator grid)");
    save_png(fig,folder,lower(replace(estimators(ei),[" ","-"],"_"))+"_maps");
end
plot_group(distance,'distance_bin',folder,'error_vs_distance_source_comparison');
plot_group(purity,'purity_bin',folder,'error_vs_purity_source_comparison');
regions=unique(spectral(:,{'condition','region'}),'rows','stable');
fig=figure('Visible','off','Color','w','Position',[50 50 1400 1200]); tiledlayout(height(regions),2,'TileSpacing','compact');
for i=1:height(regions)
    r=radial(radial.observed_component=="Uz"&radial.condition==regions.condition(i)&radial.region==regions.region(i),:);
    nexttile; hold on;
    for source=["Z","X"]
        q=r(r.source_polarization==source,:); plot(q.k_rad_m,q.normalized_energy,'LineWidth',1.4,'DisplayName',"SOURCE-"+source);
        xline(median(q.k_q,'omitnan'),':','HandleVisibility','off');
    end
    xline(2*pi*400/1.74,'k--','k soft'); xline(2*pi*400/3.05,'k:','k stiff'); grid on;
    title(regions.condition(i)+" "+regions.region(i),'Interpreter','none'); ylabel('Normalized E(k)');
    nexttile; hold on;
    for source=["Z","X"]
        q=r(r.source_polarization==source,:); plot(q.k_rad_m,q.cumulative_energy,'LineWidth',1.4,'DisplayName',"SOURCE-"+source);
        sr=spectral(spectral.source_polarization==source&spectral.observed_component=="Uz"&spectral.condition==regions.condition(i)&spectral.region==regions.region(i),:);
        if ~isempty(sr), plot(sr.k_q,sr.q_pred,'o','HandleVisibility','off'); end
    end
    ylim([0 1]); grid on; ylabel('C(k)');
end
legend('Location','best'); sgtitle('SOURCE-Z versus SOURCE-X spectra observed through Uz'); save_png(fig,folder,'radial_and_cumulative_spectra');
end

function plot_group(t,field,folder,stem)
fig=figure('Visible','off','Color','w'); hold on; cats=unique(string(t.(field)),'stable');
for source=["Z","X"]
    q=t(t.source_polarization==source&t.estimator=="REQ-ML Q0",:); y=nan(size(cats));
    for i=1:numel(cats), row=q(string(q.(field))==cats(i),:); if ~isempty(row), y(i)=mean(row.MAPE_percent,'omitnan'); end, end
    plot(1:numel(cats),y,'-o','LineWidth',1.5,'DisplayName',"SOURCE-"+source);
end
xticks(1:numel(cats)); xticklabels(cats); ylabel('MAPE (%)'); grid on; legend; save_png(fig,folder,stem);
end

function save_png(fig,folder,stem)
exportgraphics(fig,fullfile(folder,string(stem)+".png"),'Resolution',220); close(fig);
end

function write_manifest(root,c,config_file,model_file,products,geometry)
runtime=0;
