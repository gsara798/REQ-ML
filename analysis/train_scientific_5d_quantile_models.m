function validate_q_target(q_true)

if any(~isfinite(q_true))
    error("reqml:NonFiniteQuantileTarget", ...
        "Quantile target contains non-finite rows.");
end

if any(q_true < 0 | q_true > 1)
    error("reqml:QuantileTargetOutsideUnitInterval", ...
        "Quantile target contains values outside [0,1].");
end

end

function validate_input_paths( ...
    dataset_path, split_path, purity_prediction_path)

paths = [
    dataset_path
    split_path
    purity_prediction_path
    ];

for index = 1:numel(paths)
    if ~isfile(paths(index))
        error("reqml:TrainingInputNotFound", ...
            "Required training input was not found: %s", ...
            paths(index));
    end
end

end

function prepare_output_directory(output_directory)

if ~isfolder(output_directory)
    mkdir(output_directory);
    return
end

existing = dir(fullfile(output_directory, "**", "*"));
existing = existing(~[existing.isdir]);

if ~isempty(existing)
    error("reqml:QuantileTrainingOutputAlreadyExists", ...
        ["Quantile output already contains files. Delete it only " ...
         "when intentionally rerunning version v1: %s"], ...
        output_directory);
end

end

function write_json(path, value)

text = jsonencode(value, PrettyPrint=true);

file_id = fopen(path, "w");

if file_id < 0
    error("reqml:CannotWriteJson", ...
        "Could not open JSON file for writing: %s", path);
end

cleanup = onCleanup(@() fclose(file_id));
fprintf(file_id, "%s\n", text);

end
