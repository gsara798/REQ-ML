function audit_scientific_5d_dataset()
%AUDIT_SCIENTIFIC_5D_DATASET Audit the final accumulated 5-D dataset.

repo_root = fileparts(fileparts(mfilename("fullpath")));

dataset_file = fullfile( ...
    repo_root, ...
    "outputs", ...
    "adaptive_scientific_5d", ...
    "reqml_adaptive_scientific_5d_final", ...
    "reqml_adaptive_scientific_5d_final_iteration_050", ...
    "dataset", ...
    "examples.mat");

output_directory = fullfile( ...
    repo_root, ...
    "outputs", ...
    "adaptive_scientific_5d", ...
    "reqml_adaptive_scientific_5d_final", ...
    "audit");

figure_directory = fullfile(output_directory, "figures");
table_directory = fullfile(output_directory, "tables");

if ~isfile(dataset_file)
    error( ...
        "reqml:Scientific5DDatasetNotFound", ...
        "Final dataset was not found: %s", ...
        dataset_file);
end

if ~isfolder(figure_directory)
    mkdir(figure_directory);
end

if ~isfolder(table_directory)
    mkdir(table_directory);
end

loaded = load(dataset_file);

if ~isfield(loaded, "examples") || ~istable(loaded.examples)
    error( ...
        "reqml:InvalidScientific5DDataset", ...
        "examples.mat must contain an examples table.");
end

examples = loaded.examples;

required_variables = [
    "example_id"
    "campaign_run_id"
    "campaign_condition_id"
    "q_local_req"
    "q_pred"
    "q_target_from_center_truth"
    "q_theory_discrete"
    "GRID_dx_m"
    "GRID_dz_m"
    "achieved_sws_bin"
    "achieved_frequency_bin"
    "achieved_purity_bin"
    "achieved_dnom_bin"
    "achieved_discretization_bin"
    "achieved_purity"
    ];

missing = setdiff( ...
    required_variables, ...
    string(examples.Properties.VariableNames));

if ~isempty(missing)
    error( ...
        "reqml:MissingScientific5DAuditVariable", ...
        "Dataset is missing required variables: %s", ...
        strjoin(missing, ", "));
end

q_target = double(examples.q_target_from_center_truth);
q_local = double(examples.q_local_req);
q_pred = double(examples.q_pred);
q_theory = double(examples.q_theory_discrete);

valid_target = isfinite(q_target);
valid_local = isfinite(q_local);

if ~all(valid_target)
    warning( ...
        "reqml:NonfiniteScientific5DTargets", ...
        "%d nonfinite target quantiles were found.", ...
        nnz(~valid_target));
end

%% Dataset integrity

dataset_integrity = table( ...
    height(examples), ...
    numel(unique(string(examples.example_id))), ...
    numel(unique(string(examples.campaign_run_id))), ...
    numel(unique(string(examples.campaign_condition_id))), ...
    height(examples) - numel(unique(string(examples.example_id))), ...
    nnz(valid_target), ...
    nnz(~valid_target), ...
    nnz(q_target < 0 | q_target > 1), ...
    nnz(q_target == 0), ...
    nnz(q_target == 1), ...
    max(abs(q_pred - q_local), [], "omitnan"), ...
    nnz(isfinite(q_theory)), ...
    nnz(isfinite(q_theory)) / height(examples), ...
    VariableNames=[ ...
        "example_count", ...
        "unique_example_count", ...
        "unique_run_count", ...
        "unique_condition_count", ...
        "duplicate_example_id_count", ...
        "finite_target_count", ...
        "nonfinite_target_count", ...
        "target_outside_unit_interval_count", ...
        "target_exactly_zero_count", ...
        "target_exactly_one_count", ...
        "maximum_q_pred_q_local_difference", ...
        "finite_theory_count", ...
        "finite_theory_fraction"]);

writetable( ...
    dataset_integrity, ...
    fullfile(table_directory, "dataset_integrity.csv"));

disp("===== DATASET INTEGRITY =====");
disp(dataset_integrity);

%% Global quantile summary

percentile_levels = [ ...
    0
    0.1
    1
    5
    25
    50
    75
    95
    99
    99.9
    100];

target_percentiles = prctile( ...
    q_target(valid_target), ...
    percentile_levels);

local_percentiles = prctile( ...
    q_local(valid_local), ...
    percentile_levels);

quantile_percentiles = table( ...
    percentile_levels, ...
    target_percentiles(:), ...
    local_percentiles(:), ...
    VariableNames=[ ...
        "percentile", ...
        "q_target", ...
        "q_local_req"]);

writetable( ...
    quantile_percentiles, ...
    fullfile(table_directory, "quantile_percentiles.csv"));

global_quantile_summary = table( ...
    min(q_target, [], "omitnan"), ...
    max(q_target, [], "omitnan"), ...
    mean(q_target, "omitnan"), ...
    median(q_target, "omitnan"), ...
    std(q_target, "omitnan"), ...
    min(q_local, [], "omitnan"), ...
    max(q_local, [], "omitnan"), ...
    mean(q_local, "omitnan"), ...
    median(q_local, "omitnan"), ...
    std(q_local, "omitnan"), ...
    VariableNames=[ ...
        "q_target_minimum", ...
        "q_target_maximum", ...
        "q_target_mean", ...
        "q_target_median", ...
        "q_target_standard_deviation", ...
        "q_local_minimum", ...
        "q_local_maximum", ...
        "q_local_mean", ...
        "q_local_median", ...
        "q_local_standard_deviation"]);

writetable( ...
    global_quantile_summary, ...
    fullfile(table_directory, "global_quantile_summary.csv"));

disp("===== TARGET QUANTILE PERCENTILES =====");
disp(quantile_percentiles);

%% Spacing summary

spacing_summary = groupsummary( ...
    examples, ...
    [ ...
        "achieved_discretization_bin", ...
        "GRID_dx_m", ...
        "GRID_dz_m"], ...
    { ...
        "min", ...
        "median", ...
        "max", ...
        "mean", ...
        "std"}, ...
    "q_target_from_center_truth");

spacing_summary.q05 = splitapply( ...
    @(x) prctile(x, 5), ...
    q_target, ...
    findgroups( ...
        examples.achieved_discretization_bin, ...
        examples.GRID_dx_m, ...
        examples.GRID_dz_m));

spacing_summary.q95 = splitapply( ...
    @(x) prctile(x, 95), ...
    q_target, ...
    findgroups( ...
        examples.achieved_discretization_bin, ...
        examples.GRID_dx_m, ...
        examples.GRID_dz_m));

spacing_summary.q90_range = ...
    spacing_summary.q95 - spacing_summary.q05;

writetable( ...
    spacing_summary, ...
    fullfile(table_directory, "quantile_summary_by_spacing.csv"));

disp("===== QUANTILE SUMMARY BY SPACING =====");
disp(spacing_summary);

%% Five-dimensional cell summary

cell_group_variables = [
    "achieved_sws_bin"
    "achieved_frequency_bin"
    "achieved_purity_bin"
    "achieved_dnom_bin"
    "achieved_discretization_bin"
    ];

[group_id, ...
    sws_bin, ...
    frequency_bin, ...
    purity_bin, ...
    dnom_bin, ...
    discretization_bin] = findgroups( ...
        examples.achieved_sws_bin, ...
        examples.achieved_frequency_bin, ...
        examples.achieved_purity_bin, ...
        examples.achieved_dnom_bin, ...
        examples.achieved_discretization_bin);

cell_example_count = splitapply(@numel, q_target, group_id);
cell_q_minimum = splitapply(@min, q_target, group_id);
cell_q05 = splitapply(@(x) prctile(x, 5), q_target, group_id);
cell_q25 = splitapply(@(x) prctile(x, 25), q_target, group_id);
cell_q50 = splitapply(@median, q_target, group_id);
cell_q75 = splitapply(@(x) prctile(x, 75), q_target, group_id);
cell_q95 = splitapply(@(x) prctile(x, 95), q_target, group_id);
cell_q_maximum = splitapply(@max, q_target, group_id);
cell_q_standard_deviation = splitapply(@std, q_target, group_id);

cell_summary = table( ...
    sws_bin, ...
    frequency_bin, ...
    purity_bin, ...
    dnom_bin, ...
    discretization_bin, ...
    cell_example_count, ...
    cell_q_minimum, ...
    cell_q05, ...
    cell_q25, ...
    cell_q50, ...
    cell_q75, ...
    cell_q95, ...
    cell_q_maximum, ...
    cell_q_standard_deviation);

cell_summary.q90_range = ...
    cell_summary.cell_q95 - cell_summary.cell_q05;

cell_summary.iqr = ...
    cell_summary.cell_q75 - cell_summary.cell_q25;

cell_summary.cell_key = compose( ...
    "s%02d_f%02d_p%02d_d%02d_g%02d", ...
    cell_summary.sws_bin, ...
    cell_summary.frequency_bin, ...
    cell_summary.purity_bin, ...
    cell_summary.dnom_bin, ...
    cell_summary.discretization_bin);

cell_summary = movevars( ...
    cell_summary, ...
    "cell_key", ...
    "Before", ...
    1);

writetable( ...
    cell_summary, ...
    fullfile(table_directory, "quantile_summary_by_5d_cell.csv"));

%% Extreme examples

[~, ascending_order] = sort(q_target, "ascend");
[~, descending_order] = sort(q_target, "descend");

extreme_count = min(25, height(examples));

extreme_indices = [
    ascending_order(1:extreme_count)
    descending_order(1:extreme_count)
    ];

extreme_role = [
    repmat("lowest_q_target", extreme_count, 1)
    repmat("highest_q_target", extreme_count, 1)
    ];

extreme_variables = [
    "example_id"
    "campaign_run_id"
    "campaign_condition_id"
    "q_target_from_center_truth"
    "q_local_req"
    "q_theory_discrete"
    "truth_cs_center_m_s"
    "campaign_frequency_hz"
    "achieved_purity"
    "achieved_sws_bin"
    "achieved_frequency_bin"
    "achieved_purity_bin"
    "achieved_dnom_bin"
    "achieved_discretization_bin"
    "GRID_dx_m"
    "GRID_dz_m"
    "center_selection_role"
    ];

extreme_examples = examples( ...
    extreme_indices, ...
    extreme_variables);

extreme_examples.extreme_role = extreme_role;

extreme_examples = movevars( ...
    extreme_examples, ...
    "extreme_role", ...
    "Before", ...
    1);

writetable( ...
    extreme_examples, ...
    fullfile(table_directory, "extreme_quantile_examples.csv"));

%% Figure 1: target and local quantile histograms

figure_handle = figure( ...
    Visible="off", ...
    Position=[100 100 1000 650]);

histogram( ...
    q_target(valid_target), ...
    BinEdges=0:0.025:1, ...
    Normalization="probability", ...
    DisplayName="q target");

hold on;

histogram( ...
    q_local(valid_local), ...
    BinEdges=0:0.025:1, ...
    Normalization="probability", ...
    DisplayStyle="stairs", ...
    LineWidth=1.8, ...
    DisplayName="q local REQ");

xlabel("Quantile");
ylabel("Probability");
title("Global quantile distributions");
legend(Location="northwest");
grid on;
xlim([0 1]);

exportgraphics( ...
    figure_handle, ...
    fullfile(figure_directory, "quantile_histograms.png"), ...
    Resolution=200);

close(figure_handle);

%% Figure 2: empirical cumulative distributions

figure_handle = figure( ...
    Visible="off", ...
    Position=[100 100 1000 650]);

[f_target, x_target] = ecdf(q_target(valid_target));
[f_local, x_local] = ecdf(q_local(valid_local));

plot( ...
    x_target, ...
    f_target, ...
    LineWidth=2, ...
    DisplayName="q target");

hold on;

plot( ...
    x_local, ...
    f_local, ...
    LineWidth=2, ...
    DisplayName="q local REQ");

xlabel("Quantile");
ylabel("Empirical cumulative probability");
title("Empirical cumulative quantile distributions");
legend(Location="northwest");
grid on;
xlim([0 1]);
ylim([0 1]);

exportgraphics( ...
    figure_handle, ...
    fullfile(figure_directory, "quantile_ecdf.png"), ...
    Resolution=200);

close(figure_handle);

%% Figure 3: target quantile by grid spacing

spacing_label = compose( ...
    "%.2f mm", ...
    1000 * examples.GRID_dx_m);

figure_handle = figure( ...
    Visible="off", ...
    Position=[100 100 1000 650]);

boxchart( ...
    categorical(spacing_label), ...
    q_target);

xlabel("Grid spacing");
ylabel("q target");
title("Target quantile by spatial discretization");
grid on;
ylim([0 1]);

exportgraphics( ...
    figure_handle, ...
    fullfile(figure_directory, "q_target_by_grid_spacing.png"), ...
    Resolution=200);

close(figure_handle);

%% Figure 4: target quantile by SWS bin

figure_handle = figure( ...
    Visible="off", ...
    Position=[100 100 1000 650]);

boxchart( ...
    categorical(examples.achieved_sws_bin), ...
    q_target);

xlabel("SWS coverage bin");
ylabel("q target");
title("Target quantile by SWS bin");
grid on;
ylim([0 1]);

exportgraphics( ...
    figure_handle, ...
    fullfile(figure_directory, "q_target_by_sws_bin.png"), ...
    Resolution=200);

close(figure_handle);

%% Figure 5: median target quantile across SWS and frequency

spacing_bins = unique( ...
    examples.achieved_discretization_bin, ...
    "sorted");

sws_bins = unique( ...
    examples.achieved_sws_bin, ...
    "sorted");

frequency_bins = unique( ...
    examples.achieved_frequency_bin, ...
    "sorted");

figure_handle = figure( ...
    Visible="off", ...
    Position=[100 100 1500 500]);

layout = tiledlayout( ...
    1, ...
    numel(spacing_bins), ...
    TileSpacing="compact", ...
    Padding="compact");

for spacing_index = 1:numel(spacing_bins)
    nexttile;

    spacing_bin = spacing_bins(spacing_index);

    median_matrix = nan( ...
        numel(sws_bins), ...
        numel(frequency_bins));

    for sws_index = 1:numel(sws_bins)
        for frequency_index = 1:numel(frequency_bins)
            mask = ...
                examples.achieved_discretization_bin == spacing_bin & ...
                examples.achieved_sws_bin == sws_bins(sws_index) & ...
                examples.achieved_frequency_bin == ...
                    frequency_bins(frequency_index);

            if any(mask)
                median_matrix(sws_index, frequency_index) = ...
                    median(q_target(mask), "omitnan");
            end
        end
    end

    imagesc( ...
        frequency_bins, ...
        sws_bins, ...
        median_matrix);

    set(gca, YDir="normal");
    clim([0.5 0.95]);
    colorbar;

    xlabel("Frequency bin");
    ylabel("SWS bin");

    spacing_value = median( ...
        examples.GRID_dx_m( ...
            examples.achieved_discretization_bin == spacing_bin));

    title(sprintf( ...
        "Grid %.2f mm", ...
        1000 * spacing_value));
end

title(layout, "Median q target by SWS, frequency, and grid spacing");

exportgraphics( ...
    figure_handle, ...
    fullfile( ...
        figure_directory, ...
        "q_target_sws_frequency_heatmaps.png"), ...
    Resolution=200);

close(figure_handle);

%% Figure 6: target quantile versus achieved purity

dnom_bins = unique( ...
    examples.achieved_dnom_bin, ...
    "sorted");

figure_handle = figure( ...
    Visible="off", ...
    Position=[100 100 1400 900]);

layout = tiledlayout( ...
    2, ...
    ceil(numel(dnom_bins) / 2), ...
    TileSpacing="compact", ...
    Padding="compact");

for dnom_index = 1:numel(dnom_bins)
    nexttile;

    dnom_bin = dnom_bins(dnom_index);
    mask = examples.achieved_dnom_bin == dnom_bin;

    scatter( ...
        examples.achieved_purity(mask), ...
        q_target(mask), ...
        14, ...
        examples.achieved_discretization_bin(mask), ...
        "filled", ...
        MarkerFaceAlpha=0.35);

    xlabel("Achieved material purity");
    ylabel("q target");
    title(sprintf("Angular coverage bin %d", dnom_bin));
    grid on;
    xlim([0 1]);
    ylim([0 1]);
end

colorbar;
title(layout, "Target quantile versus achieved purity");

exportgraphics( ...
    figure_handle, ...
    fullfile( ...
        figure_directory, ...
        "q_target_vs_purity_by_angularity.png"), ...
    Resolution=200);

close(figure_handle);

%% Figure 7: cell-level quantile variability

figure_handle = figure( ...
    Visible="off", ...
    Position=[100 100 1000 650]);

histogram( ...
    cell_summary.q90_range, ...
    30);

xlabel("Within-cell q95 - q05");
ylabel("Number of 5-D cells");
title("Target quantile variability within 5-D coverage cells");
grid on;

exportgraphics( ...
    figure_handle, ...
    fullfile( ...
        figure_directory, ...
        "within_cell_quantile_range.png"), ...
    Resolution=200);

close(figure_handle);

%% Save audit workspace

save( ...
    fullfile(output_directory, "audit_summary.mat"), ...
    "dataset_integrity", ...
    "global_quantile_summary", ...
    "quantile_percentiles", ...
    "spacing_summary", ...
    "cell_summary", ...
    "extreme_examples", ...
    "-v7.3");

fprintf("\nAudit completed.\n");
fprintf("Tables: %s\n", table_directory);
fprintf("Figures: %s\n", figure_directory);

end
