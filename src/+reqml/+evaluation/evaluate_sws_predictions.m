function metrics = evaluate_sws_predictions( ...
    sws_table, partition, model_id)
%EVALUATE_SWS_PREDICTIONS Compute SWS metrics by data partition.

arguments
    sws_table table
    partition (:,1) string
    model_id (1,1) string
end

required = [
    "cs_true_m_s"
    "cs_pred_m_s"
    "cs_error_m_s"
    "cs_error_percent"
    "cs_absolute_error_percent"
    "sws_valid"
    ];

missing = setdiff( ...
    required, ...
    string(sws_table.Properties.VariableNames));

if ~isempty(missing)
    error("reqml:InvalidSwsPredictionTable", ...
        "SWS table is missing variables: %s", ...
        strjoin(missing, ", "));
end

if numel(partition) ~= height(sws_table)
    error("reqml:PredictionSizeMismatch", ...
        "Partition must contain one value per SWS row.");
end

partition_names = ["train", "validation", "test"];
rows = cell(numel(partition_names), 1);

for index = 1:numel(partition_names)
    name = partition_names(index);

    mask = ...
        partition == name & ...
        logical(sws_table.sws_valid);

    if ~any(mask)
        error("reqml:EmptyEvaluationPartition", ...
            "Partition '%s' has no valid SWS rows.", name);
    end

    rows{index} = table( ...
        model_id, ...
        name, ...
        nnz(partition == name), ...
        nnz(mask), ...
        mean(abs(sws_table.cs_error_m_s(mask)), "omitnan"), ...
        sqrt(mean(sws_table.cs_error_m_s(mask).^2, "omitnan")), ...
        mean(sws_table.cs_error_m_s(mask), "omitnan"), ...
        median(sws_table.cs_absolute_error_percent(mask), "omitnan"), ...
        mean(sws_table.cs_absolute_error_percent(mask), "omitnan"), ...
        mean(sws_table.cs_error_percent(mask), "omitnan"), ...
        max(sws_table.cs_absolute_error_percent(mask)), ...
        'VariableNames', [ ...
            "model_id", ...
            "partition", ...
            "row_count", ...
            "valid_row_count", ...
            "sws_mae_m_s", ...
            "sws_rmse_m_s", ...
            "sws_bias_m_s", ...
            "sws_median_ape", ...
            "sws_mape", ...
            "sws_bias_percent", ...
            "sws_max_ape"]);
end

metrics = vertcat(rows{:});

end
