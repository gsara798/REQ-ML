function metrics = evaluate_sws_predictions( ...
    sws_table, partition, model_id)
%EVALUATE_SWS_PREDICTIONS Compute SWS metrics by data partition.
%
% Model selection should prioritize SWS performance rather than q error
% alone. The report therefore includes central error, bias, tail error,
% and clinically/practically relevant error-rate thresholds.

arguments
    sws_table table
    partition (:,1) string
    model_id (1,1) string
end

required = [
    "cs_true_m_s"
    "cs_pred_m_s"
    "cs_error_m_s"
    "cs_error_percent"
    "cs_absolute_error_percent"
    "sws_valid"
    ];

missing = setdiff( ...
    required, ...
    string(sws_table.Properties.VariableNames));

if ~isempty(missing)
    error("reqml:InvalidSwsPredictionTable", ...
        "SWS table is missing variables: %s", ...
        strjoin(missing, ", "));
end

if numel(partition) ~= height(sws_table)
    error("reqml:PredictionSizeMismatch", ...
        "Partition must contain one value per SWS row.");
end

partition_names = ["train", "validation", "test"];
rows = cell(numel(partition_names), 1);

for index = 1:numel(partition_names)
    name = partition_names(index);

    partition_mask = partition == name;

    valid_mask = ...
        partition_mask & ...
        logical(sws_table.sws_valid);

    if ~any(valid_mask)
        error("reqml:EmptyEvaluationPartition", ...
            "Partition '%s' has no valid SWS rows.", name);
    end

    error_m_s = ...
        double(sws_table.cs_error_m_s(valid_mask));

    error_percent = ...
        double(sws_table.cs_error_percent(valid_mask));

    absolute_error_percent = ...
        double(sws_table.cs_absolute_error_percent(valid_mask));

    rows{index} = table( ...
        model_id, ...
        name, ...
        nnz(partition_mask), ...
        nnz(valid_mask), ...
        mean(abs(error_m_s), "omitnan"), ...
        sqrt(mean(error_m_s.^2, "omitnan")), ...
        mean(error_m_s, "omitnan"), ...
        median(absolute_error_percent, "omitnan"), ...
        mean(absolute_error_percent, "omitnan"), ...
        mean(error_percent, "omitnan"), ...
        prctile(absolute_error_percent, 90), ...
        prctile(absolute_error_percent, 95), ...
        max(absolute_error_percent), ...
        100 * mean(absolute_error_percent > 5), ...
        100 * mean(absolute_error_percent > 10), ...
        100 * mean(absolute_error_percent > 20), ...
        100 * mean(error_percent < 0), ...
        'VariableNames', [ ...
            "model_id", ...
            "partition", ...
            "row_count", ...
            "valid_row_count", ...
            "sws_mae_m_s", ...
            "sws_rmse_m_s", ...
            "sws_bias_m_s", ...
            "sws_median_ape", ...
            "sws_mape", ...
            "sws_bias_percent", ...
            "sws_p90_ape", ...
            "sws_p95_ape", ...
            "sws_max_ape", ...
            "sws_error_gt5_pct", ...
            "sws_error_gt10_pct", ...
            "sws_error_gt20_pct", ...
            "sws_underestimate_pct"]);
end

metrics = vertcat(rows{:});

end
