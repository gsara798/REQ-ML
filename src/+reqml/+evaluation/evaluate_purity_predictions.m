function metrics = evaluate_purity_predictions( ...
    purity_true, purity_pred, partition, model_id)
%EVALUATE_PURITY_PREDICTIONS Compute purity metrics by partition.

arguments
    purity_true (:,1) double
    purity_pred (:,1) double
    partition (:,1) string
    model_id (1,1) string
end

n = numel(purity_true);

if numel(purity_pred) ~= n || numel(partition) ~= n
    error("reqml:PredictionSizeMismatch", ...
        "Truth, predictions, and partitions must have equal length.");
end

partition_names = ["train", "validation", "test"];
rows = cell(numel(partition_names), 1);

for index = 1:numel(partition_names)
    name = partition_names(index);

    mask = ...
        partition == name & ...
        isfinite(purity_true) & ...
        isfinite(purity_pred);

    if ~any(mask)
        error("reqml:EmptyEvaluationPartition", ...
            "Partition '%s' has no valid purity rows.", name);
    end

    residual = purity_pred(mask) - purity_true(mask);

    rows{index} = table( ...
        model_id, ...
        name, ...
        nnz(partition == name), ...
        nnz(mask), ...
        mean(abs(residual), "omitnan"), ...
        sqrt(mean(residual.^2, "omitnan")), ...
        mean(residual, "omitnan"), ...
        median(abs(residual), "omitnan"), ...
        prctile(abs(residual), 90), ...
        prctile(abs(residual), 95), ...
        max(abs(residual)), ...
        'VariableNames', [ ...
            "model_id", ...
            "partition", ...
            "row_count", ...
            "valid_row_count", ...
            "purity_mae", ...
            "purity_rmse", ...
            "purity_bias", ...
            "purity_median_ae", ...
            "purity_p90_ae", ...
            "purity_p95_ae", ...
            "purity_max_ae"]);
end

metrics = vertcat(rows{:});

end
