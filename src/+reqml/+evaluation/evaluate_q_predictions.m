function metrics = evaluate_q_predictions( ...
    q_true, ...
    q_pred, ...
    partition, ...
    baseline_id)
%EVALUATE_Q_PREDICTIONS Compute q metrics independently by partition.

arguments
    q_true (:,1) double
    q_pred (:,1) double
    partition (:,1) string
    baseline_id (1,1) string
end

n = numel(q_true);

if numel(q_pred) ~= n || numel(partition) ~= n
    error("reqml:PredictionSizeMismatch", ...
        "Truth, predictions, and partitions must have equal length.");
end

allowed = ["train", "validation", "test"];

unexpected = setdiff(unique(partition), allowed);

if ~isempty(unexpected)
    error("reqml:UnknownEvaluationPartition", ...
        "Unknown partitions: %s", strjoin(unexpected, ", "));
end

metrics = table();

for index = 1:numel(allowed)
    partition_name = allowed(index);
    mask = partition == partition_name;

    valid = ...
        mask & ...
        isfinite(q_true) & ...
        isfinite(q_pred);

    if ~any(valid)
        error("reqml:EmptyEvaluationPartition", ...
            "Partition '%s' has no valid prediction rows.", ...
            partition_name);
    end

    residual = q_pred(valid) - q_true(valid);

    row = table( ...
        baseline_id, ...
        partition_name, ...
        nnz(mask), ...
        nnz(valid), ...
        mean(abs(residual), "omitnan"), ...
        sqrt(mean(residual.^2, "omitnan")), ...
        mean(residual, "omitnan"), ...
        median(abs(residual), "omitnan"), ...
        max(abs(residual)), ...
        'VariableNames', [ ...
            "baseline_id", ...
            "partition", ...
            "row_count", ...
            "valid_row_count", ...
            "q_mae", ...
            "q_rmse", ...
            "q_bias", ...
            "q_median_ae", ...
            "q_max_ae"]);

    metrics = [metrics; row]; %#ok<AGROW>
end

end
