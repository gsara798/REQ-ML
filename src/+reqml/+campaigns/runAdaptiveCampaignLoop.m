function result = runAdaptiveCampaignLoop( ...
    previous_csv, initial_batch_directory, ...
    feat_cfg, campaign_config, ...
    simulation_framework_root, options)
%RUNADAPTIVECAMPAIGNLOOP Execute and advance an adaptive campaign.
%
% Workflow:
%
%   existing accumulated CSV
%       + initial planned simulation batch
%       -> execute simulations
%       -> merge campaign CSVs
%       -> rebuild dataset
%       -> recompute coverage
%       -> plan next batch
%       -> repeat until complete or iteration limit
%
% The initial batch must already contain:
%
%   adaptive_batch_plan.json
%   simulation_campaign_*.json

arguments
    previous_csv (1,1) string
    initial_batch_directory {mustBeTextScalar}
    feat_cfg (1,1) struct
    campaign_config (1,1) struct
    simulation_framework_root {mustBeTextScalar}

    options.OutputRoot {mustBeTextScalar}
    options.CampaignId (1,1) string

    options.MaximumIterations (1,1) double = 10
    options.PlannerSeed (1,1) double = 1

    options.PurityEdges (1,:) double
    options.DiffusivityEdges (1,:) double
    options.SwsEdges (1,:) double
    options.FrequencyEdges (1,:) double

    options.MinimumExamples (1,1) double = 500
    options.MinimumIndependentRuns (1,1) double = 5
    options.MinimumSwsBins (1,1) double = 3
    options.MinimumFrequencyBins (1,1) double = 3
    options.MinimumIndependentConditions (1,1) double = 3
    options.MinimumGeometrySeeds (1,1) double = 0

    options.MaximumConditions (1,1) double = 20
    options.RealizationsPerCondition (1,1) double = 2

    options.Resume (1,1) logical = true
    options.ContinueOnError (1,1) logical = false

    % Dependency injection allows orchestration tests without running
    % real simulations or rebuilding full datasets.
    options.ExecuteBatchFunction (1,1) function_handle = ...
        @reqml.campaigns.executeAdaptiveBatch

    options.AdvanceIterationFunction (1,1) function_handle = ...
        @reqml.campaigns.advanceAdaptiveIteration
end

validate_inputs( ...
    previous_csv, ...
    initial_batch_directory, ...
    options);

output_root = string(options.OutputRoot);

if ~isfolder(output_root)
    [created, message] = mkdir(output_root);

    if ~created
        error("reqml:AdaptiveLoopOutputCreateFailed", ...
            "Could not create output root '%s': %s", ...
            output_root, message);
    end
end

current_csv = previous_csv;
current_batch_directory = ...
    string(initial_batch_directory);

records = repmat( ...
    empty_iteration_record(), ...
    options.MaximumIterations, ...
    1);

completed_iteration_count = 0;
stop_reason = "maximum_iterations_reached";
coverage_complete = false;

for iteration_index = 1:options.MaximumIterations
    iteration_id = sprintf( ...
        "%s_iteration_%03d", ...
        options.CampaignId, ...
        iteration_index);

    iteration_directory = fullfile( ...
        output_root, ...
        iteration_id);

    executed_plan_file = fullfile( ...
        current_batch_directory, ...
        "adaptive_batch_plan.json");

    if ~isfile(executed_plan_file)
        error("reqml:AdaptiveBatchPlanNotFound", ...
            "Adaptive batch plan was not found: %s", ...
            executed_plan_file);
    end

    fprintf( ...
        "\n============================================================\n");
    fprintf( ...
        "Adaptive iteration %d of %d\n", ...
        iteration_index, ...
        options.MaximumIterations);
    fprintf("Batch: %s\n", current_batch_directory);

    execution = feval( ...
        options.ExecuteBatchFunction, ...
        current_batch_directory, ...
        simulation_framework_root, ...
        Resume=options.Resume, ...
        ContinueOnError=options.ContinueOnError);

    next_campaign_config = campaign_config;

    next_campaign_config.campaign_name = sprintf( ...
        "%s_simulation_%03d", ...
        options.CampaignId, ...
        iteration_index + 1);

    iteration_seed = ...
        options.PlannerSeed + iteration_index - 1;

    advanced = feval( ...
        options.AdvanceIterationFunction, ...
        current_csv, ...
        execution.campaign_csv_files, ...
        feat_cfg, ...
        next_campaign_config, ...
        OutputDirectory=iteration_directory, ...
        IterationId=iteration_id, ...
        PlannerSeed=iteration_seed, ...
        PurityEdges=options.PurityEdges, ...
        DiffusivityEdges=options.DiffusivityEdges, ...
        SwsEdges=options.SwsEdges, ...
        FrequencyEdges=options.FrequencyEdges, ...
        MinimumExamples=options.MinimumExamples, ...
        MinimumIndependentRuns= ...
            options.MinimumIndependentRuns, ...
        MinimumSwsBins=options.MinimumSwsBins, ...
        MinimumFrequencyBins= ...
            options.MinimumFrequencyBins, ...
        MinimumIndependentConditions= ...
            options.MinimumIndependentConditions, ...
        MinimumGeometrySeeds= ...
            options.MinimumGeometrySeeds, ...
        MaximumConditions=options.MaximumConditions, ...
        RealizationsPerCondition= ...
            options.RealizationsPerCondition, ...
        ParentCoverageReportHash= ...
            string(iteration_index - 1), ...
        ExecutedBatchPlanFile= ...
            executed_plan_file);

    record = empty_iteration_record();

    record.iteration_index = iteration_index;
    record.iteration_id = iteration_id;
    record.batch_directory = current_batch_directory;
    record.iteration_directory = string(iteration_directory);

    record.executed_campaign_count = ...
        double(execution.campaign_count);

    record.executed_run_count = ...
        double(execution.run_count);

    record.accumulated_run_count = ...
        double(advanced.accumulated_run_count);

    record.example_count = ...
        double(advanced.iteration.example_count);

    record.observed_coverage_cell_count = ...
        double( ...
            advanced.iteration. ...
                observed_coverage_cell_count);

    record.deficient_cell_count = ...
        double(advanced.iteration.deficient_cell_count);

    record.coverage_complete = ...
        logical(advanced.iteration.coverage_complete);

    record.next_batch_required = ...
        logical( ...
            advanced.iteration.planning.batch_required);

    record.accumulated_campaign_csv = ...
        string( ...
            advanced.paths. ...
                accumulated_campaign_csv);

    records(iteration_index) = record;
    completed_iteration_count = iteration_index;

    fprintf( ...
        "Executed runs: %d\n", ...
        record.executed_run_count);

    fprintf( ...
        "Accumulated runs: %d\n", ...
        record.accumulated_run_count);

    fprintf( ...
        "Examples: %d\n", ...
        record.example_count);

    fprintf( ...
        "Observed cells: %d\n", ...
        record.observed_coverage_cell_count);

    fprintf( ...
        "Deficient cells: %d\n", ...
        record.deficient_cell_count);

    coverage_complete = ...
        record.coverage_complete;

    if coverage_complete
        stop_reason = "coverage_complete";
        break
    end

    if ~record.next_batch_required
        stop_reason = "no_next_batch_required";
        break
    end

    next_batch_directory = fullfile( ...
        iteration_directory, ...
        "next_batch");

    if ~isfolder(next_batch_directory)
        error("reqml:AdaptiveNextBatchNotFound", ...
            ["Planner reported that another batch was required, " ...
             "but the next_batch directory was not created: %s"], ...
            next_batch_directory);
    end

    current_csv = ...
        record.accumulated_campaign_csv;

    current_batch_directory = ...
        string(next_batch_directory);
end

records = records(1:completed_iteration_count);

result = struct();

result.schema_name = ...
    "reqml_adaptive_campaign_loop";

result.schema_version = "1.0";
result.campaign_id = options.CampaignId;

result.completed_iteration_count = ...
    completed_iteration_count;

result.maximum_iterations = ...
    options.MaximumIterations;

result.stop_reason = stop_reason;
result.coverage_complete = coverage_complete;

result.iterations = records;

if completed_iteration_count > 0
    result.final_accumulated_campaign_csv = ...
        records(end).accumulated_campaign_csv;

    result.final_iteration_directory = ...
        records(end).iteration_directory;

    result.final_deficient_cell_count = ...
        records(end).deficient_cell_count;
else
    result.final_accumulated_campaign_csv = "";
    result.final_iteration_directory = "";
    result.final_deficient_cell_count = NaN;
end

result.paths = persist_loop_result( ...
    result, ...
    output_root);

end


function paths = persist_loop_result(result, output_root)

summary_path = fullfile( ...
    output_root, ...
    "adaptive_loop_summary.json");

iterations_path = fullfile( ...
    output_root, ...
    "adaptive_loop_iterations.csv");

write_json_atomically( ...
    summary_path, ...
    result);

iteration_table = ...
    iteration_records_to_table( ...
        result.iterations);

writetable( ...
    iteration_table, ...
    iterations_path);

paths = struct();

paths.summary_json = ...
    string(summary_path);

paths.iterations_csv = ...
    string(iterations_path);

end


function iteration_table = ...
        iteration_records_to_table(records)

if isempty(records)
    iteration_table = table();
    return
end

records = records(:);
row_count = numel(records);

iteration_table = table();

iteration_table.iteration_index = reshape( ...
    [records.iteration_index], ...
    row_count, ...
    1);

iteration_table.iteration_id = reshape( ...
    string({records.iteration_id}), ...
    row_count, ...
    1);

iteration_table.batch_directory = reshape( ...
    string({records.batch_directory}), ...
    row_count, ...
    1);

iteration_table.iteration_directory = reshape( ...
    string({records.iteration_directory}), ...
    row_count, ...
    1);

iteration_table.executed_campaign_count = reshape( ...
    [records.executed_campaign_count], ...
    row_count, ...
    1);

iteration_table.executed_run_count = reshape( ...
    [records.executed_run_count], ...
    row_count, ...
    1);

iteration_table.accumulated_run_count = reshape( ...
    [records.accumulated_run_count], ...
    row_count, ...
    1);

iteration_table.example_count = reshape( ...
    [records.example_count], ...
    row_count, ...
    1);

iteration_table.observed_coverage_cell_count = reshape( ...
    [records.observed_coverage_cell_count], ...
    row_count, ...
    1);

iteration_table.deficient_cell_count = reshape( ...
    [records.deficient_cell_count], ...
    row_count, ...
    1);

iteration_table.coverage_complete = reshape( ...
    logical([records.coverage_complete]), ...
    row_count, ...
    1);

iteration_table.next_batch_required = reshape( ...
    logical([records.next_batch_required]), ...
    row_count, ...
    1);

iteration_table.accumulated_campaign_csv = reshape( ...
    string({records.accumulated_campaign_csv}), ...
    row_count, ...
    1);

end


function write_json_atomically(path_value, value)

temporary_path = ...
    string(path_value) + ".tmp";

if isfile(temporary_path)
    delete(temporary_path);
end

file_id = fopen(temporary_path, "w");

if file_id < 0
    error("reqml:AdaptiveLoopSummaryWriteFailed", ...
        "Could not create temporary file '%s'.", ...
        temporary_path);
end

cleanup = onCleanup(@() fclose(file_id));

fprintf(file_id, "%s", ...
    jsonencode(value, PrettyPrint=true));

clear cleanup

[moved, message] = movefile( ...
    temporary_path, ...
    path_value, ...
    "f");

if ~moved
    if isfile(temporary_path)
        delete(temporary_path);
    end

    error("reqml:AdaptiveLoopSummaryWriteFailed", ...
        "Could not publish loop summary '%s': %s", ...
        path_value, ...
        message);
end

end


function validate_inputs( ...
        previous_csv, initial_batch_directory, options)

if ~isfile(previous_csv)
    error("reqml:AdaptiveLoopPreviousCsvNotFound", ...
        "Previous accumulated CSV was not found: %s", ...
        previous_csv);
end

if ~isfolder(initial_batch_directory)
    error("reqml:AdaptiveLoopInitialBatchNotFound", ...
        "Initial batch directory was not found: %s", ...
        initial_batch_directory);
end

if strlength(options.CampaignId) == 0
    error("reqml:InvalidAdaptiveLoopCampaignId", ...
        "CampaignId must be non-empty.");
end

if options.MaximumIterations < 1 || ...
        options.MaximumIterations ~= ...
            fix(options.MaximumIterations)

    error("reqml:InvalidAdaptiveLoopIterationLimit", ...
        "MaximumIterations must be a positive integer.");
end

end


function record = empty_iteration_record()

record = struct();

record.iteration_index = 0;
record.iteration_id = "";
record.batch_directory = "";
record.iteration_directory = "";

record.executed_campaign_count = 0;
record.executed_run_count = 0;
record.accumulated_run_count = 0;
record.example_count = 0;

record.observed_coverage_cell_count = 0;
record.deficient_cell_count = 0;

record.coverage_complete = false;
record.next_batch_required = false;

record.accumulated_campaign_csv = "";

end
